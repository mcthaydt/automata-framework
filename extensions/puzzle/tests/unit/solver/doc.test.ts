// `analyse`, the lock graph and the generated doc (M6 spec §4.5): the adventure source's two cases on the toy scene.
import { describe, expect, it } from 'vitest'
import { analyse, lockGraph, renderDoc, stamp } from '#src/entries/solver.ts'
import { toyScene } from '#src/testing/toy-scene.ts'

describe('puzzle doc', () => {
  const p = toyScene()
  const x = analyse(p)

  it('derives the lock graph from the routes', () => {
    expect(lockGraph(p, x.routes).edges).toEqual([
      { from: 'drawer.open', to: 'door.unlock', label: '+key' },
      { from: 'door.unlock', to: 'goal', label: 'doorOpen' },
    ])
  })

  it('writes the same doc every time, stamped with the sources, with every section', () => {
    const doc = renderDoc(p, x)
    expect(renderDoc(p, analyse(p))).toBe(doc)
    expect(doc.split('\n')[0]).toMatch(/Generated by .*Do not edit/)
    expect(doc).toContain(stamp(p))
    for (const section of [
      '## Solver findings',
      '## Routes',
      '## Lock graph',
      '```mermaid',
      '## Actions',
      '## Items × hotspots',
      '## Lethal rules and hints',
    ])
      expect(doc).toContain(section)
    // 2 s + 3 s of actions; 3 m then 4 m of walking at 3 m/s.
    expect(doc).toContain('| shortest | 2 | 5.0 s | 2.3 s | 7.3 s (0:07) |')
    expect(doc).toContain('| 2 | `door.unlock` | Use the Key on the Door |')
  })
})
