// The generated puzzle doc, from the adventure source's `renderDoc`: the solver's findings, the routes
// with their times, the lock graph, the actions, the item × hotspot matrix, the systemic set-ups and the lethal rules.
// Stamped with its sources' XXH64 hashes, so `check` can tell a stale doc.
import type { Effect } from '../../shared/sim/puzzle.schema'
import type { Cond, Value } from '../../shared/sim/value.schema'
import { type Analysis, keypadOf, keySet, timing } from './analyse'
import { GOAL, lockGraph } from './lock-graph'
import { matrix } from './matrix'
import type { Step } from './model'
import type { PuzzleScene } from './scene'
import { used } from './validate'

const val = (v: Value): string => (typeof v === 'string' ? `'${v}'` : String(v))
/** A condition in words, for the generated doc. */
export function showCond(c: Cond): string {
  if ('has' in c) return `has ${c.has}`
  if ('not' in c) return `not ${showCond(c.not)}`
  if ('any' in c) return `(${c.any.map(showCond).join(' or ')})`
  const parts: string[] = []
  if (c.is !== undefined) parts.push(`${c.fact} = ${val(c.is)}`)
  if (c.atLeast !== undefined)
    parts.push(c.atLeast === Number.MIN_VALUE ? `${c.fact} > 0` : `${c.fact} ≥ ${c.atLeast}`)
  if (c.atMost !== undefined) parts.push(`${c.fact} ≤ ${c.atMost}`)
  return parts.join(', ') || `${c.fact} set`
}
/** An effect in words, for the generated doc. */
export function showEffect(e: Effect): string {
  if ('set' in e) return `${e.set} = ${val(e.to)}`
  if ('add' in e) return `${e.add} += ${e.by}`
  if ('give' in e) return `+${e.give}`
  if ('take' in e) return `−${e.take}`
  if ('noise' in e) return `noise ${e.noise.kind} (${e.noise.loudness} m)`
  if ('cutscene' in e) return `cutscene ${e.cutscene}`
  if ('checkpoint' in e) return 'checkpoint'
  if ('keypad' in e) return 'keypad'
  if ('exit' in e) return `exit to ${e.exit.to}`
  if ('dialogue' in e) return `dialogue ${e.dialogue}`
  return `call ${e.call}`
}
const cell = (s: string): string => s.replace(/\|/g, '\\|').replace(/\n/g, ' ')
const code = (s: string): string => (s === '' ? '' : `\`${s}\``)
const secs = (s: number): string => `${s.toFixed(1)} s`
const clock = (s: number): string => `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, '0')}`

/** What the player does for a step, in words. */
export function describe(p: PuzzleScene, step: Step): string {
  const item = (id: string) => p.story.items[id] ?? id
  const spot = (id: string) => p.names[id] ?? id
  if (step.systemic === true)
    return `(systemic) ${p.def.systemic.find((s) => `systemic:${s.id}` === step.action)?.note ?? step.action}`
  if (step.at === 'code') {
    const k = keypadOf(p)
    return `Type ${step.code ?? ''} at the ${k === undefined ? 'keypad' : spot(k)}`
  }
  if (step.at === 'combine')
    return `Combine the ${item(step.pair?.[0] ?? '')} with the ${item(step.pair?.[1] ?? '')}`
  if (step.at === 'floor') return `Use the ${item(step.held ?? '')} on the floor`
  return step.held === undefined
    ? `Click the ${spot(step.at)}`
    : `Use the ${item(step.held)} on the ${spot(step.at)}`
}
/** The line that records which source files the generated doc was made from, with their hashes. */
export const stamp = (p: PuzzleScene): string =>
  `sources: ${p.sources.map((s) => `${s.path} xxh64 ${s.hash}`).join('; ')}`
/** The name of the generated doc file, `puzzle.md`. */
export const DOC = 'puzzle.md'

/**
 * Writes a scene's puzzle doc as Markdown from its analysis: the hotspots, the item table, the
 * routes with their times, the softlocks and the lock graph.
 */
export function renderDoc(p: PuzzleScene, x: Analysis): string {
  const { def } = p
  const L: string[] = []
  const mermaidId = (id: string) => id.replace(/[^A-Za-z0-9]/g, '_')
  L.push(
    `<!-- Generated by \`automata pipe puzzle run ${p.id}\`. Do not edit: change the puzzle and regenerate. -->`,
    `<!-- ${stamp(p)} -->`,
    '',
    `# ${p.id}: puzzle (generated)`,
    '',
    `> Generated from the puzzle's content and its solver model by the puzzle pipeline. Do not edit this file: change the puzzle, then run the pipeline again. \`automata pipe puzzle check\` fails when this doc is older than its sources.`,
    '',
    `- **Goal:** ${def.goal.map(showCond).join(', ')}`,
    `- **Entries:** ${def.entry.map((e) => `${e.name} (${e.items.join(', ') || 'nothing'})`).join('; ')}`,
    `- **Size:** ${def.actions.length} actions, ${Object.keys(def.facts).length} facts, ${def.items.length} items, ${def.systemic.length} systemic set-ups, ${def.lethal.length} lethal rules`,
    '',
  )
  const shortest = x.routes[0]
  L.push('## Solver findings', '')
  L.push(
    `- **Solvable:** ${x.solve.solvable ? 'yes' : '**no**'}; ${x.solve.states} states for the shortest solution${x.solve.capped ? ' (**capped**)' : ''}.`,
  )
  L.push(
    `- **Softlocks:** ${x.softlocks.count}${x.softlocks.capped ? ' (search **capped**)' : ''} over ${x.softlocks.states} reachable states.`,
  )
  L.push(`- **Routes:** ${x.routes.length} distinct key-sets (the shortest, and one per alternative key).`)
  for (const r of x.routes.slice(1)) {
    const fresh = r.solution.steps
      .map((s) => s.action)
      .filter((a) => !(shortest?.solution.steps ?? []).some((s) => s.action === a))
    L.push(`  - ${r.name}: ${fresh.map(code).join(', ')}`)
  }
  const single = [...new Set(shortest?.solution.steps.map((s) => s.action) ?? [])].filter((id) =>
    x.solve.alternatives.some((a) => a.banned === id && a.solution === null),
  )
  if (single.length > 0)
    L.push(`- **Single keys** (banning one leaves no solution): ${single.map(code).join(', ')}.`)
  if (x.keys.length > 0)
    L.push(
      `- **Key-sets the design asks for:** ${x.keys.filter((k) => k.ok).length} of ${x.keys.length} found${
        x.keys.every((k) => k.ok)
          ? ''
          : ` (**missing**: ${x.keys
              .filter((k) => !k.ok)
              .map((k) => `${k.lock}: ${k.key}`)
              .join(', ')})`
      }.`,
    )
  L.push(
    `- **Hints:** ${
      x.hints.every((h) => h.ok)
        ? 'every lethal rule is hinted before its risk'
        : `**failing**: ${x.hints
            .filter((h) => !h.ok)
            .map((h) => h.id)
            .join(', ')}`
    }.`,
  )
  const fastest = x.routes
    .map((r) => ({ r, t: timing(p, r.solution) }))
    .sort((a, b) => a.t.total - b.t.total)[0]
  if (fastest !== undefined)
    L.push(
      `- **Budget floor:** ${secs(fastest.t.total)} (${clock(fastest.t.total)}) on the fastest route (${fastest.r.name}): ${secs(fastest.t.actions)} of actions, ${secs(fastest.t.walking)} walking at 3 m/s. A first-time player's time (exploring, reading, the NPCs) is not modelled.`,
    )
  if (x.softlocks.never.length > 0)
    L.push(
      `- **Never taken** in any reachable state (dead data, or a gap in the model): ${x.softlocks.never.map(code).join(', ')}.`,
    )
  L.push('')
  L.push(
    '## Routes',
    '',
    'Times: action `seconds` plus walking between hotspots with every door open, at 3 m/s.',
    '',
  )
  L.push('| Route | Steps | Actions | Walking | Total |', '| --- | --- | --- | --- | --- |')
  for (const r of x.routes) {
    const t = timing(p, r.solution)
    L.push(
      `| ${r.name} | ${r.solution.steps.length} | ${secs(t.actions)} | ${secs(t.walking)} | ${secs(t.total)} (${clock(t.total)}) |`,
    )
  }
  L.push('')
  for (const r of x.routes) {
    L.push(`### ${r.name}`, '', '| # | Action | What the player does |', '| --- | --- | --- |')
    r.solution.steps.forEach((s, i) => {
      L.push(`| ${i + 1} | ${code(s.action)} | ${cell(describe(p, s))} |`)
    })
    L.push('')
  }
  if (x.keys.length > 0) {
    L.push(
      '## Key-sets',
      '',
      "Each lock and the keys the design asks for (the model's `keys`): the shortest solution with the other keys banned must take the key's steps.",
      '',
      '| Lock | Key | Takes | Banned | Route | |',
      '| --- | --- | --- | --- | --- | --- |',
    )
    for (const k of x.keys) {
      const solution = k.solution
      const route =
        solution === null ? '—' : (x.routes.find((r) => keySet(r.solution) === keySet(solution))?.name ?? '—')
      L.push(
        `| ${cell(k.lock)} | ${cell(k.key)} | ${k.uses.map(code).join(', ')} | ${(k.ban ?? []).map(code).join(', ') || '—'} | ${cell(route)} | ${k.ok ? 'ok' : `**missing** ${k.missing.map(code).join(', ') || 'no solution'}`} |`,
      )
    }
    L.push('')
  }
  const graph = lockGraph(p, x.routes)
  const onShortest = new Set(shortest?.solution.steps.map((s) => s.action) ?? [])
  L.push(
    '## Lock graph',
    '',
    'Derived from the routes: an arrow reads "is needed for", labelled with what it provides. Thick nodes are on the shortest route.',
    '',
    '```mermaid',
    'flowchart TD',
  )
  for (const n of graph.nodes) L.push(`  ${mermaidId(n)}["${n}"]`)
  L.push(`  ${GOAL}(["goal: ${def.goal.map(showCond).join(', ').replace(/"/g, "'")}"])`)
  for (const e of graph.edges)
    L.push(
      `  ${mermaidId(e.from)} -->${e.label === '' ? '' : `|"${e.label.replace(/"/g, "'")}"|`} ${mermaidId(e.to)}`,
    )
  if (onShortest.size > 0)
    L.push(
      '  classDef shortest stroke-width:3px',
      `  class ${[...onShortest].map(mermaidId).join(',')} shortest`,
    )
  L.push('```', '')
  L.push(
    '## Actions',
    '',
    "In order of precedence: a verb takes the first action whose place, item and conditions match. An omitted item matches whatever the player holds; `held` is the item in hand (`''` for a bare hand) and `code` the typed code.",
    '',
  )
  L.push('| ID | At | Use | When | Then | Says | s |', '| --- | --- | --- | --- | --- | --- | --- |')
  for (const a of def.actions)
    L.push(
      `| ${code(a.id)} | ${a.at} | ${cell(used(a).join(' + '))} | ${cell((a.when ?? []).map(showCond).join('; '))} | ${cell(a.then.map(showEffect).join('; '))} | ${code(a.say)} | ${a.seconds ?? p.model.seconds ?? 2} |`,
    )
  L.push(
    '',
    `Fallback lines: ${Object.keys(def.fallback)
      .sort()
      .map((at) => `${at} → ${code(def.fallback[at] as string)}`)
      .join(', ')}.`,
    '',
  )
  const m = matrix(def)
  L.push(
    '## Items × hotspots',
    '',
    'A cell names the actions for that item there; *any* is a response whatever the player holds; — is the fallback line.',
    '',
  )
  L.push(`| Item | ${m.hotspots.join(' | ')} |`, `| --- | ${m.hotspots.map(() => '---').join(' | ')} |`)
  for (const row of m.rows)
    L.push(
      `| ${row.item} | ${m.hotspots
        .map((h) => {
          const c = row.cells[h] ?? 'fallback'
          return c === 'any' ? '*any*' : c === 'fallback' ? '—' : cell(c)
        })
        .join(' | ')} |`,
    )
  L.push(
    '',
    `Combines: ${m.combines.map((c) => `${c.pair.join(' + ')} → ${code(c.action)}`).join(', ') || 'none'}.`,
    '',
  )
  L.push('## Systemic set-ups', '', '| ID | Note | Via | Enables | Risk |', '| --- | --- | --- | --- | --- |')
  for (const s of def.systemic)
    L.push(
      `| ${code(s.id)} | ${cell(s.note)} | ${s.via.map(code).join(', ')} | ${cell(s.enables.map(showCond).join('; '))} | ${s.risk ?? '—'} |`,
    )
  L.push(
    '',
    '## Lethal rules and hints',
    '',
    "Every route must reach one of a rule's hints before the first step that exposes its risk.",
    '',
    '| ID | Rule | Hinted by | Status |',
    '| --- | --- | --- | --- |',
  )
  for (const l of def.lethal) {
    const h = x.hints.find((y) => y.id === l.id)
    L.push(
      `| ${code(l.id)} | ${cell(l.rule)} | ${l.hintedBy.map(code).join(', ')} | ${h?.ok === true ? 'ok' : cell(`failing: ${(h?.failures ?? []).join('; ')}`)} |`,
    )
  }
  L.push('')
  return L.join('\n')
}
