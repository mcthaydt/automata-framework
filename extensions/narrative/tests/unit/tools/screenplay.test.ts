// The act screenplay: the review artifact, one section
// per scene of the act: its shortest solver route as played in the sim, the lines, items, cutscene captions and
// conversations in play order, with each beat marked where it lands. Pure and deterministic: the same traces give
// byte-identical text.
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { describe, expect, it } from 'vitest'
import type { DialogueGraph, LineRecord } from '#src/entries/sim.ts'
import { beatCoverage } from '#src/features/tools/coverage.ts'
import {
  dialogueScreenplay,
  type ScreenplayScene,
  screenplay,
  storyletRows,
} from '#src/features/tools/screenplay.ts'
import { play, solverRoutes, type Trace, traces } from '#src/features/tools/traces.ts'
import type { Beat } from '#src/shared/beats.schema.ts'
import { TOY_RECORDS, TOY_STORYLETS, TOY_TEXT, toyTraceGame } from '#src/testing/toy-trace.ts'

const records: LineRecord[] = [
  { id: 'toy.cutscene.opening.1', kind: 'caption', text: 'toy.cutscene.opening.1', beat: 'toy.wake' },
  { id: 'toy.bed', kind: 'examine', speaker: 'ada', text: 'toy.bed', beat: 'toy.wake' },
  { id: 'toy.key', kind: 'note', text: 'toy.key' },
  { id: 'toy.item.key.name', kind: 'item', text: 'toy.item.key.name' },
  { id: 'toy.item.key', kind: 'item', speaker: 'ada', text: 'toy.item.key' },
]
const text = {
  'toy.cutscene.opening.1': 'A ward. 04:17.',
  'toy.bed': 'Bed 04.\nStill warm.',
  'toy.key': 'SUPPLY',
  'toy.item.key.name': 'Brass key',
  'toy.item.key': 'Still warm.',
}
const trace: Trace = {
  route: 'shortest',
  entry: 'start',
  goal: true,
  events: [
    { kind: 'cutscene', id: 'opening', duration: 12, captions: ['toy.cutscene.opening.1'], at: 0 },
    { kind: 'step', n: 1, action: 'bed.search', text: 'Click the Bed', at: 12 },
    { kind: 'line', id: 'toy.bed', title: 'Bed', at: 14.5 },
    { kind: 'step', n: 2, action: 'tag.read', text: 'Click the Tag', at: 61 },
    { kind: 'line', id: 'toy.key', title: 'Tag', at: 63 },
    { kind: 'item', item: 'key', name: 'toy.item.key.name', text: 'toy.item.key', at: 63 },
  ],
}
const beats: Beat[] = [
  { id: 'toy.wake', learn: 'She wakes.', required: true, deliveredBy: ['toy.cutscene.opening.1', 'toy.bed'] },
  { id: 'toy.note', learn: 'A note.', required: false, deliveredBy: ['toy.note'] },
]
const scene: ScreenplayScene = {
  scene: 'toy',
  title: 'Toy Ward',
  trace,
  routes: ['shortest', 'other'],
  beats,
  coverage: beatCoverage(beats, [trace]).beats,
  records,
  text,
}
const STAMP = 'sources: toy sha256 0'
const make = (scenes: ScreenplayScene[] = [scene]) =>
  screenplay('act-one', scenes, STAMP, 'automata pipe narrative screenplay')

describe('screenplay', () => {
  it('is stamped, and writes captions, lines, items and beats in play order, and the beats found off the route', () => {
    const md = make()
    expect(md.split('\n').slice(0, 2)).toEqual([
      '<!-- Generated by `automata pipe narrative screenplay`. Do not edit: change the lines, beats or cutscenes and regenerate. -->',
      `<!-- ${STAMP} -->`,
    ])
    const order = [
      'Cutscene: opening (12 s)',
      '*A ward. 04:17.*',
      'Beat `toy.wake`',
      '### 0:12 · 1. Click the Bed',
      '**ADA** *(Bed)*: Bed 04. / Still warm.',
      '### 1:01 · 2. Click the Tag',
      '> SUPPLY — *(Tag)*',
      '**[ Brass key ]** Still warm.',
      '### Off the route',
    ]
    const at = order.map((s) => md.indexOf(s))
    expect(at.every((i) => i >= 0)).toBe(true)
    expect([...at].sort((a, b) => a - b)).toEqual(at)
    expect(md.match(/Beat `toy.wake`/g)).toHaveLength(1)
    expect(md).toContain('| `toy.note` | no | — | 0/2 | A note. |')
  })
  it('gives byte-identical text for the same traces', () => {
    expect(make()).toBe(make())
  })
  it('marks a beat a conversation delivers, on every path, where the conversation is, and not off the route', () => {
    const graph: DialogueGraph = {
      id: 'toy.talk',
      speaker: 'porter',
      start: 'ask',
      nodes: {
        ask: {
          say: ['toy.ask'],
          choices: [
            { line: 'toy.yes', next: 'end' },
            { line: 'toy.no', next: 'end' },
          ],
        },
        end: { say: [] },
      },
    }
    const lines: LineRecord[] = [
      ...records,
      { id: 'toy.ask', kind: 'dialogue', speaker: 'porter', text: 'toy.ask' },
      { id: 'toy.yes', kind: 'dialogue', speaker: 'ada', text: 'toy.yes' },
      { id: 'toy.no', kind: 'dialogue', speaker: 'ada', text: 'toy.no' },
    ]
    const words = { ...text, 'toy.ask': 'Staff, or for me?', 'toy.yes': 'Staff.', 'toy.no': 'For you.' }
    const talk: Trace = {
      ...trace,
      events: [...trace.events, { kind: 'dialogue', id: 'toy.talk', said: ['toy.ask'], at: 70 }],
    }
    const both: Beat[] = [
      ...beats,
      { id: 'toy.meet', learn: 'He asks.', required: true, deliveredBy: ['toy.ask'] },
      { id: 'toy.chose', learn: 'She answers.', required: false, deliveredBy: ['toy.yes'] },
    ]
    const coverage = beatCoverage(both, [talk]).beats
    const md = make([
      { ...scene, trace: talk, beats: both, coverage, records: lines, text: words, dialogues: [graph] },
    ])
    const off = md.slice(md.indexOf('### Off the route'))
    expect(md.indexOf('> ▸ **Beat `toy.meet`** (required)')).toBeGreaterThan(
      md.indexOf('### Dialogue: toy.talk'),
    )
    // Off the route is exactly what coverage says this route misses: a choice's line is not said on every path.
    expect([...off.matchAll(/^- \*\*`([^`]+)`/gm)].map((m) => m[1])).toEqual(
      coverage.filter((b) => !b.delivered.includes('shortest')).map((b) => b.id),
    )
    expect(off).toContain('`toy.chose`')
    expect(off).not.toContain('`toy.meet`')
  })
  it('shows an unrecorded message as such, and a caught or unknown line as having no record', () => {
    const odd: Trace = {
      ...trace,
      events: [
        { kind: 'unrecorded', text: 'Text with\nno record', at: 1 },
        { kind: 'line', id: 'toy.nope', title: 'X', at: 2 },
      ],
    }
    const md = make([{ ...scene, trace: odd }])
    expect(md).toContain('> Text with / no record *(not a line record)*')
    expect(md).toContain('- *(toy.nope: no record)*')
  })
})

describe('dialogueScreenplay', () => {
  const graph: DialogueGraph = {
    id: 'meet',
    speaker: 'porter',
    start: 'open',
    nodes: {
      open: {
        say: ['toy.hello', 'toy.ask'],
        choices: [
          { line: 'toy.duty', stance: -1, next: 'join' },
          { line: 'toy.unsure', next: 'join' },
          { line: 'toy.yours', stance: 1, set: { metPorter: true }, next: 'join' },
        ],
      },
      join: { say: [], next: 'warm' },
      warm: { say: ['toy.warm'], when: [{ fact: 'light', is: 'lighter' }], next: 'bye' },
      bye: { say: ['toy.bye'] },
    },
  }
  it('shows the choices as columns, with the stance each moves, and the gates', () => {
    const md = dialogueScreenplay(graph, TOY_RECORDS, TOY_TEXT)
    expect(md).toContain('| Choice 1 | Choice 2 | Choice 3 |')
    expect(md).toContain('| ADA: Staff. | ADA: I don’t know yet. | ADA: I think I’m for you. |')
    expect(md).toContain('| stance -1 | stance 0 | stance +1; sets metPorter = true |')
    expect(md).toContain("*(only when light = 'lighter')*")
    expect(md).toContain('*(exit)*')
  })
  it('names speakers as the game says', () => {
    const md = dialogueScreenplay(graph, TOY_RECORDS, TOY_TEXT, (s) =>
      s === 'ada' ? 'Ada' : (s ?? '').toUpperCase(),
    )
    expect(md).toContain('> **PORTER:** ')
    expect(md).toContain('| Ada: Staff. |')
  })
})

describe('storyletRows and the appendix', () => {
  it('lists every storylet with its trigger in words, its limit and the routes that played it', async () => {
    const game = toyTraceGame()
    const all = await traces(game)
    const rows = storyletRows(TOY_STORYLETS, all, { names: { drawer: 'Drawer' }, player: 'Ada' })
    expect(rows).toEqual([
      {
        id: 'st.murmur',
        phase: '—',
        trigger: 'Ada examines Drawer (`drawer`), after the action’s own line',
        limit: 'once',
        when: [],
        lines: ['toy.murmur'],
        reached: ['shortest'],
      },
    ])
    const md = make([
      { ...scene, storylets: rows, records: [...records, ...TOY_RECORDS], text: { ...text, ...TOY_TEXT } },
    ])
    expect(md).toContain('## Storylets (appendix)')
    expect(md).toContain('#### `st.murmur` · — · once')
    expect(md).toContain('- **On the routes:** ✓ played on 1/2 (shortest)')
    expect(md).toContain('**ADA** `toy.murmur`: Someone has been here.')
  })
  it('says how each trigger kind reads', () => {
    const [a, b, c, d] = storyletRows(
      [
        { id: 'a', trigger: 'enter:ward', lines: ['x'], max: 3 },
        { id: 'b', trigger: 'dwell:ward:8', lines: ['x'] },
        { id: 'c', trigger: 'system:fuel.low', lines: ['x'], when: [{ fact: 'power', is: true }] },
        { id: 'd', trigger: 'inspect:bed', lines: ['x'] },
      ],
      [],
      { names: {}, player: 'the player' },
    )
    expect([a?.trigger, b?.trigger, c?.trigger, d?.trigger]).toEqual([
      'the player enters ward',
      'the player stands still in ward for 8 s',
      'the systems event `fuel.low`',
      'the player examines bed (`bed`), after the action’s own line',
    ])
    expect([a?.limit, b?.limit]).toEqual(['at most 3 times', 'every time'])
  })
})

describe('the toy scene’s screenplay', () => {
  it('matches the committed fixture, and is the same on a second play', async () => {
    const game = toyTraceGame()
    const routes = solverRoutes(game.puzzle)
    const all = await traces(game, routes)
    const shortest = all[0] as Trace
    const md = screenplay(
      'toy-act',
      [
        {
          scene: 'toy',
          title: 'Toy Ward',
          trace: shortest,
          routes: routes.map((r) => r.name),
          beats: [
            {
              id: 'toy.key',
              learn: 'The key is in the drawer.',
              required: true,
              deliveredBy: ['toy.drawer'],
            },
            {
              id: 'toy.meet',
              learn: 'The porter asks who she is.',
              required: true,
              deliveredBy: ['toy.hello'],
            },
            {
              id: 'toy.dawn',
              learn: 'It is first light.',
              required: true,
              deliveredBy: ['toy.dawn.1'],
              after: ['toy.key'],
            },
            { id: 'toy.chose', learn: 'She answers him.', required: false, deliveredBy: ['toy.duty'] },
          ],
          coverage: beatCoverage(
            [
              {
                id: 'toy.key',
                learn: 'The key is in the drawer.',
                required: true,
                deliveredBy: ['toy.drawer'],
              },
              {
                id: 'toy.meet',
                learn: 'The porter asks who she is.',
                required: true,
                deliveredBy: ['toy.hello'],
              },
              {
                id: 'toy.dawn',
                learn: 'It is first light.',
                required: true,
                deliveredBy: ['toy.dawn.1'],
                after: ['toy.key'],
              },
              { id: 'toy.chose', learn: 'She answers him.', required: false, deliveredBy: ['toy.duty'] },
            ],
            all,
          ).beats,
          records: game.records,
          text: TOY_TEXT,
          dialogues: game.graphs,
          storylets: storyletRows(TOY_STORYLETS, all, {
            names: { drawer: 'Drawer', door: 'Door' },
            player: 'Ada',
          }),
        },
      ],
      'sources: toy',
      'automata pipe narrative screenplay toy-act',
    )
    expect(md).toBe(
      readFileSync(join(import.meta.dirname, '../../../src/testing/fixtures/toy-script.md'), 'utf8'),
    )
    expect((await play(game, routes[0] as NonNullable<(typeof routes)[number]>)).events).toEqual(
      shortest.events,
    )
  })
})
