// `generate` for the blockout pipeline (M6 spec §4.11): the expansion as the scene's `sector-map` and `nav-graph` content, TOML, stamped
// on the first line with the hash of the spec text it came from. The stamp is how `check` tells a current file from a stale one, and a hand
// edit (body differs, stamp current) from both. Same spec, same bytes: no clock, no random.
import { type Blockout, expand } from '@mcthaydt/automata-sector-format/blockout'
import { hex64, utf8, xxhash64 } from '@mcthaydt/automata-sim/hash'
import { stringify } from 'smol-toml'

const STAMP = /^# blockout xxh64:([0-9a-f]{16})$/

/** The stamp line for a spec's text. */
export const specStamp = (specText: string): string => `# blockout xxh64:${hex64(xxhash64(utf8(specText)))}`

/** The stamp on a generated file's first line, or undefined when it has none. */
export function stampOf(text: string): string | undefined {
  const first = text.split('\n')[0] ?? ''
  return STAMP.test(first) ? first : undefined
}

const header = (stamp: string, what: string): string =>
  `${stamp}\n# Generated by \`automata pipe blockout\`; do not edit. ${what}\n\n`

// TOML has no undefined, and an edge's third member is the door it passes through, when it has one.
const edgeOf = (edge: readonly [string, string, (string | undefined)?]): string[] =>
  edge[2] === undefined ? [edge[0], edge[1]] : [edge[0], edge[1], edge[2]]

/** The scene's `sector-map` and `nav-graph` files for a blockout read from `specText`. */
export function generateContent(blockout: Blockout, specText: string): { map: string; nav: string } {
  const x = expand(blockout)
  const stamp = specStamp(specText)
  // JSON round trip: the content is plain data, and TOML cannot hold `undefined` members the expansion may leave.
  const plain = <T>(value: T): T => JSON.parse(JSON.stringify(value)) as T
  return {
    map:
      header(stamp, 'The scene’s sectors and masses.') +
      stringify(plain({ sectors: x.sectors, masses: x.masses })),
    nav:
      header(stamp, 'The scene’s walking graph.') +
      stringify(plain({ nodes: x.nodes, edges: x.edges.map(edgeOf) })),
  }
}
