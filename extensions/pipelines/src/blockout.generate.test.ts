import { navGraphSchema } from '@mcthaydt/automata-nav/sim'
import { expand } from '@mcthaydt/automata-sector-format/blockout'
import { sectorMapSchema } from '@mcthaydt/automata-sectors/sim'
import { parse } from 'smol-toml'
import { describe, expect, it } from 'vitest'
import { generateContent, specStamp, stampOf } from './blockout.generate.ts'
import { TOY } from './testing/toy-blockout.ts'

// `generate` (M6 spec §4.11): the expansion as `sector-map` and `nav-graph` TOML, stamped with the spec's hash so a stale or hand-edited
// file can be told from a current one. Same spec, same bytes.

const SPEC = `${JSON.stringify(TOY, null, 2)}\n`

describe('generateContent', () => {
  it('writes a sector map and a nav graph that load through their content schemas and equal the expansion', () => {
    const { map, nav } = generateContent(TOY, SPEC)
    const x = expand(TOY)
    const loadedMap = sectorMapSchema.parse(parse(map))
    expect(JSON.parse(JSON.stringify(loadedMap.sectors))).toEqual(JSON.parse(JSON.stringify(x.sectors)))
    expect(JSON.parse(JSON.stringify(loadedMap.masses ?? []))).toEqual(JSON.parse(JSON.stringify(x.masses)))
    const loadedNav = navGraphSchema.parse(parse(nav))
    expect(loadedNav.nodes).toEqual(x.nodes)
    expect(loadedNav.edges.map((e) => [e[0], e[1], ...(e[2] === undefined ? [] : [e[2]])])).toEqual(
      x.edges.map((e) => [e[0], e[1], ...(e[2] === undefined ? [] : [e[2]])]),
    )
  })

  it('is deterministic', () => {
    expect(generateContent(TOY, SPEC)).toEqual(generateContent(TOY, SPEC))
  })

  it('stamps both files on the first line with the spec’s hash, and says not to edit them', () => {
    const { map, nav } = generateContent(TOY, SPEC)
    const stamp = specStamp(SPEC)
    for (const text of [map, nav]) {
      expect(text.split('\n')[0]).toBe(stamp)
      expect(text.split('\n')[1]).toMatch(/Generated by `automata pipe blockout`; do not edit/)
      expect(stampOf(text)).toBe(stamp)
    }
  })

  it('stamps a different hash for a different spec text', () => {
    expect(specStamp(SPEC)).not.toBe(specStamp(`${SPEC} `))
    expect(specStamp(SPEC)).toMatch(/^# blockout xxh64:[0-9a-f]{16}$/)
  })

  it('has no stamp to read from a file without one', () => {
    expect(stampOf('[[sectors]]\n')).toBeUndefined()
  })
})
