// The `narrative` pipeline through the platform's router on a temporary scene folder: `run`
// writes the lint, coverage, screenplay, help doc and audit and is cached the second time; `check` passes a sound
// scene, fails a conversation with a dead end, and fails a screenplay that is stale or edited by hand. The bin runs the
// same from source.
import { spawnSync } from 'node:child_process'
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { Effect, Layer } from 'effect'
import { afterEach, describe, expect, it } from 'vitest'
import { narrativePipeline, narrativePipeSpec } from '#src/features/narrative/narrative-pipeline.ts'
import { FilesLive } from '#src/shared/node/files.ts'
import { ProcessRunnerLive } from '#src/shared/node/process.ts'
import { route } from '#src/shared/router.ts'

const resolve = createRequire(import.meta.url).resolve
const TOY = resolve('@automata/narrative/testing/toy-scene.pipe')
const DEAD_END = resolve('@automata/narrative/testing/dead-end-scene.pipe')
const temps: string[] = []
afterEach(() => {
  for (const dir of temps.splice(0)) rmSync(dir, { recursive: true, force: true })
})
function folder(module: string): string {
  const dir = mkdtempSync(join(tmpdir(), 'pipe-narrative-'))
  temps.push(dir)
  writeFileSync(join(dir, 'pipeline.toml'), '[budget]\n')
  writeFileSync(
    join(dir, 'scene.ts'),
    `export { narrative } from ${JSON.stringify(pathToFileURL(module).href)}\n`,
  )
  writeFileSync(join(dir, 'toy.lines.toml'), '# the toy lines\n')
  writeFileSync(
    join(dir, 'narrative.pipe.toml'),
    'scene = "./scene.ts"\nsources = ["toy.lines.toml"]\nact = "toy-act"\n',
  )
  return dir
}
const layers = Layer.mergeAll(FilesLive, ProcessRunnerLive)
const pipe = (...argv: string[]) =>
  Effect.runPromise(Effect.provide(route([...argv, '--json'], [narrativePipeline], []), layers)).then(
    (out) => ({
      exit: out.exit,
      json: JSON.parse(out.stdout) as Record<string, unknown>,
    }),
  )
const checks = (json: Record<string, unknown>) =>
  (json.data as { checks: { id: string; ok: boolean; detail: string }[] }).checks
const check = (json: Record<string, unknown>, id: string) => checks(json).find((c) => c.id === id)

describe('narrative.pipe.toml', () => {
  it('parses a scene module, its sources and an act; a missing scene fails at its path', () => {
    expect(
      narrativePipeSpec.safeParse({ scene: './scene.ts', sources: ['a.toml'], act: 'act-one' }).success,
    ).toBe(true)
    const bad = narrativePipeSpec.safeParse({ act: 'act-one' })
    expect(bad.success ? [] : bad.error.issues.map((i) => i.path)).toEqual([['scene']])
  })
})

describe('automata pipe narrative', () => {
  it('writes the lint, coverage, screenplay, help doc and audit, is cached the second time, and passes check', async () => {
    const dir = folder(TOY)
    const run = await pipe('narrative', 'run', dir)
    expect(run.exit).toBe(0)
    for (const file of [
      'reports/narrative-lint.json',
      'reports/narrative-coverage.json',
      'screenplay.md',
      'help.md',
      'reports/narrative-help.json',
      'reports/narrative-audit.json',
      'narrative-audit.md',
    ])
      expect(existsSync(join(dir, file)), file).toBe(true)
    expect(readFileSync(join(dir, 'screenplay.md'), 'utf8')).toMatch(/^<!-- Generated by /)
    const again = await pipe('narrative', 'run', dir)
    expect((again.json.stages as { state: string }[]).every((s) => s.state === 'skipped')).toBe(true)
    const result = await pipe('narrative', 'check', dir)
    expect(result.exit).toBe(0)
    for (const id of ['lint', 'dialogue', 'deck', 'beats', 'hints', 'help', 'screenplay', 'help-doc'])
      expect(check(result.json, id)?.ok, id).toBe(true)
  })

  it('fails check on a conversation with a dead end, naming the node', async () => {
    const dir = folder(DEAD_END)
    await pipe('narrative', 'run', dir)
    const result = await pipe('narrative', 'check', dir)
    expect(result.exit).not.toBe(0)
    expect(check(result.json, 'dialogue')).toMatchObject({ ok: false })
    expect(check(result.json, 'dialogue')?.detail).toMatch(/exit meet/)
  })

  it('fails check on a screenplay that is stale or edited by hand', async () => {
    const dir = folder(TOY)
    await pipe('narrative', 'run', dir)
    writeFileSync(join(dir, 'toy.lines.toml'), '# the toy lines, changed\n')
    expect(check((await pipe('narrative', 'check', dir)).json, 'screenplay')).toMatchObject({ ok: false })
    expect(check((await pipe('narrative', 'check', dir)).json, 'screenplay')?.detail).toMatch(/stale/)
    await pipe('narrative', 'run', dir)
    expect(check((await pipe('narrative', 'check', dir)).json, 'screenplay')?.ok).toBe(true)
    writeFileSync(
      join(dir, 'screenplay.md'),
      `${readFileSync(join(dir, 'screenplay.md'), 'utf8')}\nA note.\n`,
    )
    const edited = check((await pipe('narrative', 'check', dir)).json, 'screenplay')
    expect(edited).toMatchObject({ ok: false })
    expect(edited?.detail).toMatch(/hand/)
  })

  it('fails check when the screenplay or the help doc is missing', async () => {
    const dir = folder(TOY)
    const result = await pipe('narrative', 'check', dir)
    expect(check(result.json, 'screenplay')).toMatchObject({ ok: false, detail: 'is missing' })
    expect(check(result.json, 'help-doc')).toMatchObject({ ok: false, detail: 'is missing' })
  })
})

describe('the automata-pipe bin', () => {
  const bin = fileURLToPath(new URL('../../../src/app/cli.ts', import.meta.url))
  const personEnv = Object.fromEntries(
    Object.entries(process.env).filter(([name]) => name !== 'CLAUDECODE' && name !== 'AUTOMATA_AGENT'),
  )
  const binPipe = (...args: string[]) =>
    spawnSync(process.execPath, [bin, 'narrative', ...args, '--json'], {
      encoding: 'utf8',
      env: personEnv,
      stdio: ['ignore', 'pipe', 'pipe'],
      timeout: 120_000,
    })
  it('runs and checks a scene from source, and exits non-zero for a dead end', () => {
    const ok = folder(TOY)
    expect(binPipe('run', ok).status).toBe(0)
    const passed = binPipe('check', ok)
    // Node's type stripper warns once that it is experimental (the resolve hook strips core's source-only package itself).
    expect(passed.status).toBe(0)
    expect(JSON.parse(passed.stdout)).toMatchObject({ ok: true, command: 'check' })
    const bad = folder(DEAD_END)
    binPipe('run', bad)
    const failed = binPipe('check', bad)
    expect(failed.status).not.toBe(0)
    expect(failed.stdout).toMatch(/exit meet/)
  }, 180_000)
})
