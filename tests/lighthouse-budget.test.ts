// @vitest-environment node
import { readFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { describe, expect, it } from 'vitest'
import { medianMetrics, type LighthouseResult } from '../scripts/record-lighthouse-baseline'

// QB.3h. The first run found three pages below the targets, almost all of it total blocking time (syntax highlighting
// of code nobody could see, and a demo that started on arrival). That is fixed, so the budget now also holds total
// blocking time, and every page's budget is tightened to the run recorded after the fix (lighthouse-baseline.json was
// recorded again). LCP medians swing by about a quarter from one set of runs to the next (the home page measured 2.57
// s and 3.18 s), so the noise allowance below is a third of the LCP (it was a quarter); the budgets themselves are all
// tighter than before.
//
// QB.3f. The quality-bar spec (§4.2) asks for a Lighthouse budget on `/`, `/start`, `/examples` and `/docs`:
// performance ≥ 90 on mobile, LCP ≤ 2.5 s, CLS ≤ 0.1, with thresholds that "come from the first recorded run and are
// only tightened". The first run (lighthouse-baseline.json, generated by scripts/record-lighthouse-baseline.ts) found
// three pages below the targets, so their budgets start at that run with room for noise. The rule below keeps the
// budget honest: a page's budget may be stricter than its floor, never looser; and a page that already meets a target
// is held to the target itself.

const root = resolve(import.meta.dirname, '..')
const read = (path: string) => JSON.parse(readFileSync(resolve(root, path), 'utf8'))
const { ci } = read('lighthouserc.json')
const baseline = read('lighthouse-baseline.json') as { runsPerPage: number; pages: Record<string, { performance: number; lcpMs: number; cls: number; tbtMs: number }> }

// The spec names no blocking-time target; 200 ms is the line at which Lighthouse scores total blocking time 0.9.
const SPEC = { performance: 0.9, lcpMs: 2500, cls: 0.1, tbtMs: 200 }
// Run-to-run noise on a shared runner: a tenth of the score, a third of the LCP (QB.3h: sets of three runs minutes apart had
// medians of 2.57 s and 3.18 s on the home page and 2.26 s and 2.88 s on the gallery, so a quarter was too tight to hold CI steady).
const NOISE = { score: 0.1, lcp: 1.35 }

type Assertions = Record<string, [level: string, options: { minScore?: number; maxNumericValue?: number; aggregationMethod?: string }]>
const matrix = ci.assert.assertMatrix as { matchingUrlPattern: string; assertions: Assertions }[]
const budgetFor = (url: string): Assertions => {
  const entries = matrix.filter(entry => new RegExp(entry.matchingUrlPattern).test(url))
  expect(entries, `exactly one budget for ${url}`).toHaveLength(1)
  return entries[0]!.assertions
}

describe('the Lighthouse budget (lighthouserc.json)', () => {
  it('measures the four pages the spec names, and the baseline records the same four', () => {
    const paths = (ci.collect.url as string[]).map(url => new URL(url).pathname)
    expect(paths).toEqual(['/', '/start', '/examples', '/docs'])
    expect(Object.keys(baseline.pages)).toEqual(paths)
  })

  it('serves the built site compressed, as the host will, and starts nothing else', () => {
    expect(ci.collect.startServerCommand).toContain('scripts/serve-static.ts build')
    expect(ci.collect.startServerCommand).toContain('--compressed')
    for (const url of ci.collect.url as string[]) expect(new URL(url).hostname).toBe('127.0.0.1')
  })

  it('measures mobile, the Lighthouse default, and judges the median of at least three runs', () => {
    expect(ci.collect.settings.preset).toBeUndefined()
    expect(ci.collect.settings.formFactor).toBeUndefined()
    expect(ci.collect.numberOfRuns).toBeGreaterThanOrEqual(3)
    expect(baseline.runsPerPage).toBeGreaterThanOrEqual(3)
  })

  it('fails the build, rather than warns, on every budget line, judged by the median run', () => {
    for (const entry of matrix) {
      expect(Object.keys(entry.assertions).sort()).toEqual(['categories:performance', 'cumulative-layout-shift', 'largest-contentful-paint', 'total-blocking-time'])
      for (const [level, options] of Object.values(entry.assertions)) {
        expect(level).toBe('error')
        expect(options.aggregationMethod).toBe('median-run')
      }
    }
  })

  it.each(['/', '/start', '/examples', '/docs'])('%s: no looser than the first run allowed for noise, or than the spec when it already meets the spec', path => {
    const recorded = baseline.pages[path]!
    const budget = budgetFor(`http://127.0.0.1:4652${path}`)
    const floor = Math.min(SPEC.performance, recorded.performance - NOISE.score)
    const ceiling = Math.max(SPEC.lcpMs, recorded.lcpMs * NOISE.lcp)
    expect(budget['categories:performance']![1].minScore!).toBeGreaterThanOrEqual(floor)
    expect(budget['largest-contentful-paint']![1].maxNumericValue!).toBeLessThanOrEqual(Math.ceil(ceiling / 100) * 100)
    expect(budget['cumulative-layout-shift']![1].maxNumericValue!).toBeLessThanOrEqual(SPEC.cls)
    expect(budget['total-blocking-time']![1].maxNumericValue!).toBeLessThanOrEqual(Math.ceil(Math.max(SPEC.tbtMs, recorded.tbtMs * NOISE.lcp) / 100) * 100)
  })

  it.each(['/', '/start', '/examples', '/docs'])('%s: the recorded first run passes the budget it set', path => {
    const recorded = baseline.pages[path]!
    const budget = budgetFor(`http://127.0.0.1:4652${path}`)
    expect(recorded.performance).toBeGreaterThanOrEqual(budget['categories:performance']![1].minScore!)
    expect(recorded.lcpMs).toBeLessThanOrEqual(budget['largest-contentful-paint']![1].maxNumericValue!)
    expect(recorded.cls).toBeLessThanOrEqual(budget['cumulative-layout-shift']![1].maxNumericValue!)
    expect(recorded.tbtMs).toBeLessThanOrEqual(budget['total-blocking-time']![1].maxNumericValue!)
  })

  it.each(['/', '/start', '/examples', '/docs'])('%s: the recorded run meets the performance target and the blocking-time line', path => {
    const recorded = baseline.pages[path]!
    expect(recorded.performance).toBeGreaterThanOrEqual(SPEC.performance)
    expect(recorded.tbtMs).toBeLessThanOrEqual(SPEC.tbtMs)
  })

  it('keeps its reports as files, and uploads nothing to a third party', () => {
    expect(ci.upload.target).toBe('filesystem')
  })
})

describe('medianMetrics (the baseline recorder)', () => {
  const result = (score: number, lcp: number): LighthouseResult => ({
    lighthouseVersion: '12.6.1',
    categories: { performance: { score } },
    environment: { hostUserAgent: 'HeadlessChrome/141.0.0.0' },
    audits: Object.fromEntries(['largest-contentful-paint', 'cumulative-layout-shift', 'total-blocking-time', 'first-contentful-paint', 'speed-index', 'total-byte-weight'].map(id => [id, { numericValue: id === 'largest-contentful-paint' ? lcp : 1 }])),
  })

  it('takes each metric’s median, so one outlier run moves nothing', () => {
    const metrics = medianMetrics([result(0.9, 1000), result(0.2, 9000), result(0.91, 1100)])
    expect(metrics.performance).toBe(0.9)
    expect(metrics.lcpMs).toBe(1100)
  })

  it('refuses a run that could not score, rather than recording a guess', () => {
    expect(() => medianMetrics([{ ...result(0.9, 1000), categories: { performance: { score: null } } }])).toThrow(/could not score/)
    expect(() => medianMetrics([])).toThrow(/no Lighthouse results/)
  })
})
