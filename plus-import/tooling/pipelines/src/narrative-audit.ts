// The narrative audit (M6.8b, NR-D9): what the lints, the played routes and the generated docs say about a scene, for
// the people who decide. The platform's generic audit over the run's findings, as the puzzle's: its findings never fail
// `check` (the lints do, through their own rows; a stale doc does, through its file row). The cutscene and
// conversation audits, which read cutscenes and staging, come with the cutscenes (M6.9).
import type { FileStatus } from './puzzle-audit.ts'

export interface NarrativeFinding {
  readonly stage: string
  readonly level: 'error' | 'warning'
  readonly rule: string
  readonly id: string
  readonly detail: string
}
export interface NarrativeAudit {
  readonly scene: string
  readonly sources: readonly { readonly path: string; readonly hash: string }[]
  readonly routes: readonly { readonly name: string; readonly steps: number }[]
  readonly beats: readonly { readonly id: string; readonly required: boolean; readonly reach: number }[]
  /** Every finding of every check, errors first (they fail `check`), then warnings. */
  readonly findings: readonly NarrativeFinding[]
  readonly files: readonly FileStatus[]
}

const r2 = (n: number): number => Math.round(n * 100) / 100

export function renderAudit(a: NarrativeAudit): string {
  const errors = a.findings.filter((f) => f.level === 'error')
  const warnings = a.findings.filter((f) => f.level === 'warning')
  const L: string[] = [
    `# ${a.scene}: narrative audit (generated)`,
    '',
    '> What the narrative lints, the played routes and the generated docs say about this scene. Generated by the narrative pipeline; do not edit.',
    '',
    `- **Sources:** ${a.sources.map((s) => `\`${s.path}\` ${s.hash}`).join('; ') || 'none'}`,
    `- **Findings:** ${errors.length} errors, ${warnings.length} warnings`,
    '',
    '## Routes',
    '',
    ...a.routes.map((r) => `- **${r.name}**: ${r.steps} steps`),
    '',
    '## Beats',
    '',
    '| Beat | Required | Reach |',
    '| --- | --- | --- |',
    ...a.beats.map((b) => `| \`${b.id}\` | ${b.required ? 'yes' : 'no'} | ${r2(b.reach * 100)}% |`),
    '',
    '## Files',
    '',
    ...a.files.map((f) => `- \`${f.path}\`: ${f.ok ? 'ok' : '**not ok**'}, ${f.detail}`),
    '',
    '## Findings',
    '',
  ]
  if (a.findings.length === 0) L.push('None.', '')
  for (const f of a.findings) L.push(`- **${f.level}** \`${f.stage}\` ${f.rule} ${f.id}: ${f.detail}`)
  return `${L.join('\n')}\n`
}
