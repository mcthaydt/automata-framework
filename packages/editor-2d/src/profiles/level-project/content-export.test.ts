import { parse } from 'smol-toml'
import { describe, expect, it } from 'vitest'
import { decodeRows } from '../../model/cells-codec'
import { decodeProject } from '../../model/project-codec'
import type { Project } from '../../model/project-types'
import { richProjectFile } from '../../testing/projects'
import { contentLevelSchema, contentProjectSchema, contentWorldSchema } from './content.schema'
import { exportContent } from './content-export'

function rich(): Project {
  const decoded = decodeProject(richProjectFile())
  if (!decoded.ok) throw new Error(JSON.stringify(decoded.issues))
  return decoded.project
}

const fileOf = (project: Project, path: string): string => {
  const found = exportContent(project).find((file) => file.path === path)
  if (found === undefined) throw new Error(`no ${path} in the export`)
  return found.contents
}

describe('exportContent', () => {
  it('writes project.toml, one file per level in id order, then world.toml', () => {
    expect(exportContent(rich()).map((file) => file.path)).toEqual([
      'project.toml',
      'levels/cellar.toml',
      'levels/start.toml',
      'world.toml',
    ])
  })

  it('says in a header comment that every file is generated and from which project', () => {
    for (const file of exportContent(rich())) {
      expect(file.contents.split('\n')[0]).toBe(
        '# Generated by the Automata 2D editor from "Mossgate". Do not edit; export again.',
      )
    }
  })

  it('keeps a project name with quotes or line breaks on the one comment line', () => {
    const odd = { ...rich(), name: 'A "quoted"\nname' }
    const first = fileOf(odd, 'project.toml').split('\n')[0]
    expect(first).toBe(
      '# Generated by the Automata 2D editor from "A \\"quoted\\"\\nname". Do not edit; export again.',
    )
  })

  it('is the same bytes on every call', () => {
    const project = rich()
    expect(exportContent(project)).toEqual(exportContent(project))
  })

  describe('project.toml', () => {
    const parsed = contentProjectSchema.parse(parse(fileOf(rich(), 'project.toml')))

    it('names the project and the format', () => {
      expect([parsed.format, parsed.version, parsed.name, parsed.template]).toEqual([
        'af2d-content',
        1,
        'Mossgate',
        'platformer',
      ])
    })

    it('lists the layers in definition order with what a game needs of each', () => {
      expect(parsed.layers).toEqual([
        { id: 'entities', kind: 'entities', grid: 16, snap: true },
        { id: 'props', kind: 'objects', tileset: 'terrain', snap: 0 },
        { id: 'ground-art', kind: 'auto', grid: 16, source: 'collision', tileset: 'terrain' },
        { id: 'decor', kind: 'tiles', grid: 16, tileset: 'terrain' },
        {
          id: 'collision',
          kind: 'intgrid',
          grid: 16,
          values: [
            { value: 1, id: 'solid' },
            { value: 2, id: 'water' },
          ],
        },
      ])
    })

    it('describes a placeholder tileset by its derived size, and an imported one by its image', () => {
      expect(parsed.tilesets).toEqual([
        {
          id: 'terrain',
          tile: { w: 16, h: 16 },
          columns: 8,
          rows: 8,
          spacing: 0,
          padding: 0,
          placeholder: true,
          tags: [{ tag: 'solid', tiles: [1, 2, 3] }],
        },
      ])
      const withImage: Project = {
        ...rich(),
        defs: {
          ...rich().defs,
          tilesets: rich().defs.tilesets.map((set) => ({ ...set, image: 'assets/terrain.png' })),
        },
      }
      const imported = contentProjectSchema.parse(parse(fileOf(withImage, 'project.toml')))
      expect(imported.tilesets[0]).toEqual(
        expect.objectContaining({ image: 'assets/terrain.png', placeholder: false }),
      )
    })

    it('carries the entity definitions whole, with their typed fields, and the level fields', () => {
      const slime = parsed.entities.find((def) => def.id === 'slime')
      expect(slime).toEqual(
        expect.objectContaining({
          shape: 'ellipse',
          size: { w: 16, h: 16 },
          pivot: { x: 0.5, y: 1 },
          resizable: 'x',
          fields: [
            { id: 'hp', type: 'int', default: 3, min: 1, max: 9 },
            { id: 'patrol', type: 'point', list: true },
          ],
        }),
      )
      expect(parsed.entities.find((def) => def.id === 'player-start')).toEqual(
        expect.objectContaining({ single: true, min: { per: 'project', count: 1 } }),
      )
      expect(parsed.levelFields).toEqual([
        { id: 'music', type: 'enum', options: ['none', 'calm', 'tense'], default: 'none' },
      ])
    })
  })

  describe('levels/<id>.toml', () => {
    const project = rich()
    const level = contentLevelSchema.parse(parse(fileOf(project, 'levels/start.toml')))

    it('carries the level facts', () => {
      expect([level.id, level.name, level.size, level.fields]).toEqual([
        'start',
        'Start',
        { w: 64, h: 48 },
        { music: 'calm' },
      ])
      expect(level.background).toEqual({ color: '#1b1b2f', mode: 'fit' })
      const cellar = contentLevelSchema.parse(parse(fileOf(project, 'levels/cellar.toml')))
      expect(cellar.background).toEqual({ color: '#000000', image: 'art/cellar.png', mode: 'repeat-x' })
    })

    it('has a layer for each definition, in order', () => {
      expect(level.layers.map((layer) => [layer.def, layer.kind])).toEqual([
        ['entities', 'entities'],
        ['props', 'objects'],
        ['ground-art', 'auto'],
        ['decor', 'tiles'],
        ['collision', 'intgrid'],
      ])
    })

    it('writes tile and IntGrid layers as the row strings of the working file, which decode to the editor grids', () => {
      const source = project.levels.find((l) => l.id === 'start')
      for (const [def, kind] of [
        ['decor', 'tile'],
        ['collision', 'int'],
      ] as const) {
        const written = level.layers.find((layer) => layer.def === def)
        const original = source?.layers.find((layer) => layer.def === def)
        if (written === undefined || !('rows' in written)) throw new Error(`no rows for ${def}`)
        if (original === undefined || !('cells' in original)) throw new Error(`no cells for ${def}`)
        const decoded = decodeRows(written.rows, kind, original.cells.cols, original.cells.rows)
        expect(decoded.ok && decoded.grid.equals(original.cells)).toBe(true)
      }
    })

    it('writes entities with their typed fields: a number, a point list and a ref with its container', () => {
      const items = level.layers.find((layer) => layer.def === 'entities')
      if (items === undefined || !('items' in items)) throw new Error('no items')
      expect(items.items).toEqual([
        { id: '00000009', def: 'player-start', x: 16, y: 32, fields: {} },
        {
          id: '0000000a',
          def: 'slime',
          x: 32,
          y: 32,
          w: 24,
          fields: {
            hp: 3,
            patrol: [
              { x: 16, y: 32 },
              { x: 48, y: 32 },
            ],
          },
        },
        {
          id: '0000000c',
          def: 'door',
          x: 48,
          y: 32,
          fields: { target: { target: '0000000d', container: 'cellar' } },
        },
      ])
    })

    it('writes objects with their flips', () => {
      const props = level.layers.find((layer) => layer.def === 'props')
      if (props === undefined || !('items' in props)) throw new Error('no items')
      expect(props.items).toEqual([{ id: '0000000b', tile: 7, x: 20, y: 12, flipX: false, flipY: true }])
    })
  })

  describe('world.toml', () => {
    it('lists the worlds with their placements', () => {
      const world = contentWorldSchema.parse(parse(fileOf(rich(), 'world.toml')))
      expect(world.worlds).toEqual([
        {
          id: 'main',
          layout: 'free',
          placements: [
            { level: 'start', x: 0, y: 0, depth: 0 },
            { level: 'cellar', x: 0, y: 64, depth: 0 },
          ],
        },
      ])
    })
  })

  it('refuses a file with a key the schema does not know, so a reader cannot depend on one by accident', () => {
    const level = parse(fileOf(rich(), 'levels/start.toml'))
    expect(contentLevelSchema.safeParse({ ...level, extra: 1 }).success).toBe(false)
    expect(contentLevelSchema.safeParse({ ...level, format: 'other' }).success).toBe(false)
  })
})
