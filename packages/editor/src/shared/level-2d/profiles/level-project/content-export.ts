// Writes a level project out as the TOML files the game's content compiler reads: one per kind, each starting with a
// comment that names the project.

import type { ContentLevel, ContentProject, ContentRows, ContentWorld } from '@automata/content/level-2d'
import { stringify } from 'smol-toml'
import { encodeRows, packTile } from '../../model/cells-codec.ts'
import { Grid } from '../../model/grid.ts'
import type {
  AutoLayerInstance,
  EntitiesLayerInstance,
  LayerDef,
  LayerInstance,
  Level,
  ObjectsLayerInstance,
  Project,
} from '../../model/project-types.ts'
import { tilesetTiles } from '../../model/tileset-grid.ts'
import { worldNeighbours } from '../../model/world/world-neighbours.ts'
import { applyOverrides, autoTiles } from '../../tiles/autotile/auto-tiles.ts'
import { compileRules } from '../../tiles/autotile/match.ts'

// The AF content export: `project.toml` (the definitions a game needs), one `levels/<id>.toml`
// per level and `world.toml`. Generated, write-only and deterministic: the same project always prints the same bytes,
// and a header comment says the files are not to be edited. An auto layer is exported as its resolved tiles, so a game
// needs no rule engine. The files are validated against `content.schema.ts` in the tests.

export interface ExportFile {
  readonly path: string
  readonly contents: string
}

const FORMAT = { format: 'af2d-content', version: 1 } as const

/** One comment line. A name is JSON-quoted so a quote or a line break cannot end it early; DEL is not allowed in TOML. */
function header(name: string): string {
  const quoted = JSON.stringify(name).replaceAll('\u007f', '')
  return `# Generated by the Automata 2D editor from ${quoted}. Do not edit; export again.\n\n`
}

const print = (name: string, document: object): string => header(name) + stringify(document)

function layerDefinition(def: LayerDef): ContentProject['layers'][number] {
  switch (def.kind) {
    case 'tiles':
      return { id: def.id, kind: 'tiles', grid: def.grid, tileset: def.tileset }
    case 'intgrid':
      return {
        id: def.id,
        kind: 'intgrid',
        grid: def.grid,
        values: def.values.map((value) => ({ value: value.value, id: value.id })),
      }
    case 'auto':
      return { id: def.id, kind: 'auto', grid: def.grid, source: def.source, tileset: def.tileset }
    case 'entities':
      return { id: def.id, kind: 'entities', grid: def.grid, snap: def.snap }
    case 'objects':
      return { id: def.id, kind: 'objects', tileset: def.tileset, snap: def.snap }
  }
}

function projectDocument(project: Project): ContentProject {
  return {
    ...FORMAT,
    name: project.name,
    template: project.template,
    layers: project.defs.layers.map(layerDefinition),
    tilesets: project.defs.tilesets.map((set) => {
      const { columns, rows } = tilesetTiles(set)
      return {
        id: set.id,
        tile: set.tile,
        columns,
        rows,
        spacing: set.spacing,
        padding: set.padding,
        ...(set.image === undefined ? {} : { image: set.image }),
        placeholder: set.image === undefined,
        tags: set.tags.map((tag) => ({ tag: tag.tag, tiles: [...tag.tiles] })),
      }
    }),
    entities: project.defs.entities.map((def) => ({ ...def, fields: [...def.fields], tags: [...def.tags] })),
    levelFields: [...project.defs.levelFields],
  }
}

const entityItems = (layer: EntitiesLayerInstance): ContentLevel['layers'][number] => ({
  def: layer.def,
  kind: 'entities',
  items: layer.items.map((item) => ({
    id: item.id,
    def: item.def,
    x: item.x,
    y: item.y,
    ...(item.w === undefined ? {} : { w: item.w }),
    ...(item.h === undefined ? {} : { h: item.h }),
    fields: item.fields,
  })),
})

const objectItems = (layer: ObjectsLayerInstance): ContentLevel['layers'][number] => ({
  def: layer.def,
  kind: 'objects',
  items: layer.items.map((item) => ({ ...item })),
})

/**
 * The tiles an auto layer draws, one grid of row strings per stack depth (depth 0 is drawn first). A cell whose stack is
 * shorter than the depth is empty in that grid, and a manual override has replaced its whole stack already.
 */
function autoStack(project: Project, level: Level, layer: AutoLayerInstance): ContentRows[] {
  const def = project.defs.layers.find((candidate) => candidate.id === layer.def)
  if (def?.kind !== 'auto') return []
  const source = level.layers.find((candidate) => candidate.def === def.source)
  if (source?.kind !== 'intgrid') return []
  const result = applyOverrides(
    autoTiles(source.cells, compileRules(def.groups), layer.seed),
    layer.overrides,
  )
  // A loop, not `Math.max(...)`: a large level has more stacks than a call may take arguments.
  let depth = 0
  for (const stack of result.stacks.values()) depth = Math.max(depth, stack.length)
  return Array.from({ length: depth }, (_, index) => {
    const grid = Grid.empty(result.cols, result.rows).edit((cells) => {
      for (const [key, stack] of result.stacks) {
        const tile = stack[index]
        if (tile)
          cells.set(
            key % result.cols,
            Math.floor(key / result.cols),
            packTile(tile.tile, tile.flipX, tile.flipY),
          )
      }
    })
    return { rows: encodeRows(grid, 'tile') }
  })
}

function levelLayer(project: Project, level: Level, layer: LayerInstance): ContentLevel['layers'][number] {
  switch (layer.kind) {
    case 'tiles':
      return { def: layer.def, kind: 'tiles', rows: encodeRows(layer.cells, 'tile') }
    case 'intgrid':
      return { def: layer.def, kind: 'intgrid', rows: encodeRows(layer.cells, 'int') }
    case 'auto':
      return { def: layer.def, kind: 'auto', stack: autoStack(project, level, layer) }
    case 'entities':
      return entityItems(layer)
    case 'objects':
      return objectItems(layer)
  }
}

function levelDocument(project: Project, level: Level): ContentLevel {
  return {
    ...FORMAT,
    id: level.id,
    name: level.name,
    size: level.size,
    background: {
      color: level.background.color,
      ...(level.background.image === undefined ? {} : { image: level.background.image }),
      mode: level.background.mode,
    },
    fields: level.fields,
    layers: level.layers.map((layer) => levelLayer(project, level, layer)),
  }
}

function worldDocument(project: Project): ContentWorld {
  return {
    ...FORMAT,
    worlds: project.worlds.map((world) => ({
      id: world.id,
      layout: world.layout,
      ...(world.grid === undefined ? {} : { grid: world.grid }),
      placements: world.placements.map((placement) => ({ ...placement })),
      ...(world.layout === 'grid' ? { neighbours: worldNeighbours(project, world) } : {}),
    })),
  }
}

/** The files of the export, in the order they are listed: `project.toml`, the levels by id, then `world.toml`. */
export function exportContent(project: Project): ExportFile[] {
  const levels = [...project.levels].sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0))
  return [
    { path: 'project.toml', contents: print(project.name, projectDocument(project)) },
    ...levels.map((level) => ({
      path: `levels/${level.id}.toml`,
      contents: print(project.name, levelDocument(project, level)),
    })),
    { path: 'world.toml', contents: print(project.name, worldDocument(project)) },
  ]
}
