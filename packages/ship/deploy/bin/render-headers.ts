// Runs on the dev host (plain `node render-headers.ts`, Node 24 strips the types), called by `deploy`.
// Usage: node render-headers.ts <buildId> <headers.json>   → the build's Caddy snippet on stdout.
//
// Each build is served with the headers Ruken would serve it with: `ship deploy-dev` compiles them with
// @ruken/manifest's compileHeaders and uploads them as headers.json ({ headers, entry }). The host turns them
// into a Caddy snippet itself, instead of importing a snippet from the upload, and refuses any name or value
// that could end a header line and start Caddy config, so a tarball can set headers on its own path and
// nothing else. Cache-Control follows Ruken's cacheControlFor: the entry page is revalidated, every other
// file is immutable (build folders never change once installed).

import { readFileSync } from 'node:fs'

export interface BuildHeaders {
  readonly headers: Readonly<Record<string, string>>
  readonly entry: string
}

const BUILD_ID = /^[0-9]{12}-[0-9a-f]{7,40}$/
const HEADER_NAME = /^[A-Za-z0-9-]+$/
/** Printable ASCII without `"`, `\`, `{` or `}`: nothing that ends a quoted Caddy token or opens a block. */
const HEADER_VALUE = /^[\x20-\x7e]*$/
const UNSAFE_IN_VALUE = /["\\{}]/
const ENTRY = /^[A-Za-z0-9._-]+(?:\/[A-Za-z0-9._-]+)*$/

export function renderHeaders(buildId: string, build: BuildHeaders): string {
  if (!BUILD_ID.test(buildId)) throw new Error(`not a build ID: ${buildId}`)
  if (!ENTRY.test(build.entry) || build.entry.split('/').includes('..')) {
    throw new Error(`not a safe entry path: ${build.entry}`)
  }
  for (const [name, value] of Object.entries(build.headers)) {
    if (!HEADER_NAME.test(name)) throw new Error(`header name ${JSON.stringify(name)} is not allowed`)
    if (!HEADER_VALUE.test(value) || UNSAFE_IN_VALUE.test(value)) {
      throw new Error(`header ${name} has a value that is not allowed: ${JSON.stringify(value)}`)
    }
  }

  const matcher = `@build_${buildId.replace('-', '_')}`
  const base = `/builds/${buildId}/`
  const entryPaths = `${base} ${base}${build.entry}`
  return [
    `# Generated by deploy for build ${buildId} from its headers.json.`,
    `${matcher} path ${base}*`,
    `header ${matcher} {`,
    ...Object.entries(build.headers).map(([name, value]) => `\t${name} "${value}"`),
    '}',
    `${matcher}_entry path ${entryPaths}`,
    `header ${matcher}_entry Cache-Control "no-cache"`,
    `${matcher}_files {`,
    `\tpath ${base}*`,
    `\tnot path ${entryPaths}`,
    '}',
    `header ${matcher}_files Cache-Control "public, max-age=31536000, immutable"`,
    '',
  ].join('\n')
}

if (import.meta.main) {
  const [buildId, file] = process.argv.slice(2)
  if (buildId === undefined || file === undefined) {
    process.stderr.write('usage: render-headers.ts <buildId> <headers.json>\n')
    process.exit(2)
  }
  process.stdout.write(renderHeaders(buildId, JSON.parse(readFileSync(file, 'utf8')) as BuildHeaders))
}
