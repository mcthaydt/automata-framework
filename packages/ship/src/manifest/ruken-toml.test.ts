import { parseManifest } from '@ruken/manifest'
import { describe, expect, it } from 'vitest'
import { defineShipConfig, type ShipConfig } from '../config/ship-config.ts'
import { rukenToml } from './ruken-toml.ts'

const minimal: ShipConfig = defineShipConfig({
  game: { id: 'placeholder', title: 'Placeholder', version: '0.1.0', entry: 'index.html', sdk: '^0.0.0' },
  runtime: {
    renderer: 'canvas2d',
    orientation: 'any',
    inputs: ['touch', 'keyboard'],
    pause_behavior: 'pause',
  },
  network: { connect: [] },
  content: { languages: ['en'], rating: 'everyone', descriptors: [] },
})

function parsed(config: ShipConfig) {
  const result = parseManifest(rukenToml(config))
  if (!result.ok) throw new Error(JSON.stringify(result.errors))
  return result.manifest
}

describe('rukenToml', () => {
  it('writes a manifest Ruken accepts, with every field the config gave', () => {
    const manifest = parsed(minimal)
    expect(manifest.game).toEqual(minimal.game)
    expect(manifest.runtime).toEqual({ ...minimal.runtime, allow_eval: false })
    expect(manifest.network).toEqual({ connect: [] })
    expect(manifest.content).toEqual(minimal.content)
    expect(manifest.analytics).toEqual({ custom_events: [] })
    expect(manifest.loading).toBeUndefined()
    expect(manifest.leaderboards).toEqual({})
  })

  it('says it is generated and never allows eval', () => {
    const toml = rukenToml(minimal)
    expect(toml.split('\n')[0]).toMatch(/^# Generated by @mcthaydt\/automata-ship/)
    expect(toml).toContain('allow_eval = false')
  })

  it('writes the optional tables when the config has them', () => {
    const manifest = parsed({
      ...minimal,
      network: { connect: ['https://api.example.com', 'wss://api.example.com'] },
      content: { ...minimal.content, estimated_hours: 2 },
      analytics: { custom_events: ['level_start'] },
      loading: { preload: ['assets/splash.png', 'fonts/*'] },
      leaderboards: { 'best-time': { order: 'asc', min: 0, max: 600000 } },
    })
    expect(manifest.network.connect).toEqual(['https://api.example.com', 'wss://api.example.com'])
    expect(manifest.content.estimated_hours).toBe(2)
    expect(manifest.analytics.custom_events).toEqual(['level_start'])
    expect(manifest.loading).toEqual({ preload: ['assets/splash.png', 'fonts/*'] })
    expect(manifest.leaderboards).toEqual({ 'best-time': { order: 'asc', min: 0, max: 600000 } })
  })

  it('escapes quotes and backslashes in strings', () => {
    const manifest = parsed({ ...minimal, game: { ...minimal.game, title: 'The "Last" \\ Light' } })
    expect(manifest.game.title).toBe('The "Last" \\ Light')
  })

  it('gives the same text for the same config', () => {
    expect(rukenToml(minimal)).toBe(rukenToml(structuredClone(minimal)))
  })
})
