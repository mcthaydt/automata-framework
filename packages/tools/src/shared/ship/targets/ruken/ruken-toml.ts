import type { ShipConfig } from '../../config/ship-config.ts'

// Writes `ruken.toml` (Ruken manifest schema 1) from a ShipConfig. The file is generated at prepare time and
// never committed, so its version cannot drift from the game's (FloorFifty `deploy/tools/ruken-pack.ts`).
// Tables come in a fixed order so the same config always gives the same text.

/** A TOML basic string. JSON's escaping (\" \\ \n \uXXXX) is valid TOML for basic strings. */
const str = (value: string): string => JSON.stringify(value)

const list = (values: readonly string[]): string => `[${values.map(str).join(', ')}]`

/**
 * The text of `ruken.toml` (Ruken manifest schema 1) for a ship config. The same config always gives the same
 * text.
 */
export function rukenToml(config: ShipConfig): string {
  const { game, runtime, network, content } = config
  const lines = [
    '# Generated by @mcthaydt/automata-tools from ship.config.ts; edit that file instead.',
    'schema = 1',
    '',
    '[game]',
    `id = ${str(game.id)}`,
    `title = ${str(game.title)}`,
    `version = ${str(game.version)}`,
    `entry = ${str(game.entry)}`,
    // Optional in the game config (DIST spec §4.4): without it Ruken's parser refuses the manifest, naming `game.sdk`.
    ...(game.sdk === undefined ? [] : [`sdk = ${str(game.sdk)}`]),
    '',
    '[runtime]',
    `renderer = ${str(runtime.renderer)}`,
    `orientation = ${str(runtime.orientation)}`,
    `inputs = ${list(runtime.inputs)}`,
    `pause_behavior = ${str(runtime.pause_behavior)}`,
    // AF games never need eval: Pixi compiles shaders without it (FloorFifty v0.10.0 onward).
    'allow_eval = false',
    '',
    '[network]',
    `connect = ${list(network.connect)}`,
    '',
    '[content]',
    `languages = ${list(content.languages)}`,
    `rating = ${str(content.rating)}`,
    ...(content.estimated_hours === undefined ? [] : [`estimated_hours = ${content.estimated_hours}`]),
    `descriptors = ${list(content.descriptors)}`,
    '',
    '[analytics]',
    `custom_events = ${list(config.analytics?.custom_events ?? [])}`,
    '',
  ]
  if (config.loading !== undefined) {
    lines.push('[loading]', `preload = ${list(config.loading.preload)}`, '')
  }
  // Sorted by id so the output does not depend on the order the config listed them in.
  const boards = Object.entries(config.leaderboards ?? {}).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  for (const [id, board] of boards) {
    lines.push(
      `[leaderboards.${str(id)}]`,
      `order = ${str(board.order)}`,
      `min = ${board.min}`,
      `max = ${board.max}`,
      '',
    )
  }
  return lines.join('\n')
}
