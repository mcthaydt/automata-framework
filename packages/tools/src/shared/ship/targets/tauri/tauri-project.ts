import type { ShipConfig } from '../../config/ship-config.ts'
import type { TauriConfig } from '../../config/tauri-config.schema.ts'
import { tauriCsp } from './tauri-checks.ts'

// The Tauri project ship generates for a desktop build, written to `<game>/.automata/tauri/src-tauri/`
// on every `prepare --target tauri` and never into the game's source. The same config always gives the same files.

/**
 * The crates the generated project pins, each exactly, each released at least 14 days before it was chosen
 * (2026-10-31; `docs/versions.md`). The npm packages the adapter imports are pinned to the same releases.
 */
export const CRATE_PINS: Readonly<Record<string, string>> = {
  tauri: '2.12.4',
  'tauri-build': '2.7.3',
  'tauri-plugin-store': '2.5.0',
  'tauri-plugin-process': '2.4.0',
}

/** The window's size in CSS px by the game's orientation; the game's ui adapts to any size, and it can be resized. */
function windowSize(orientation: ShipConfig['runtime']['orientation']): { width: number; height: number } {
  return orientation === 'portrait' ? { width: 540, height: 960 } : { width: 1280, height: 720 }
}

/**
 * The files of the generated project, by path inside `src-tauri/`. `frontendDist` is the web build's folder,
 * relative to `src-tauri/`.
 */
export function tauriProjectFiles(
  config: ShipConfig,
  settings: TauriConfig,
  frontendDist: string,
): Readonly<Record<string, string>> {
  const { id, title, version } = config.game
  const conf = {
    $schema: 'https://schema.tauri.app/config/2',
    productName: title,
    version,
    identifier: settings.identifier,
    build: { frontendDist },
    app: {
      windows: [{ label: 'main', title, ...windowSize(config.runtime.orientation), resizable: true }],
      security: { csp: tauriCsp(config) },
    },
    bundle: { active: true, targets: 'all', icon: ['icons/icon.png'] },
  }
  // A crate name may not start with a digit, which a game id may.
  const crate = /^[0-9]/.test(id) ? `game-${id}` : id
  const pin = (crate: string) => `${crate} = "=${CRATE_PINS[crate]}"`
  const cargo = [
    '# Generated by @automataframework/automata-tools from ship.config.ts on every desktop build; edit that file instead.',
    '[package]',
    `name = "${crate}"`,
    `version = "${version}"`,
    'edition = "2021"',
    '',
    '[build-dependencies]',
    pin('tauri-build'),
    '',
    '[dependencies]',
    pin('tauri'),
    pin('tauri-plugin-store'),
    pin('tauri-plugin-process'),
    '',
    '[profile.release]',
    'strip = true',
    '',
  ].join('\n')
  const main = [
    '// Generated by @automataframework/automata-tools. The game is the web build; Rust only hosts it, with the store and',
    "// process plugins the desktop adapter calls (the game's saves, and Quit).",
    '#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]',
    '',
    'fn main() {',
    '    tauri::Builder::default()',
    '        .plugin(tauri_plugin_store::Builder::default().build())',
    '        .plugin(tauri_plugin_process::init())',
    '        .run(tauri::generate_context!())',
    '        .expect("the game could not start");',
    '}',
    '',
  ].join('\n')
  const capabilities = {
    identifier: 'default',
    windows: ['main'],
    permissions: ['core:default', 'store:default', 'process:allow-exit'],
  }
  return {
    'tauri.conf.json': `${JSON.stringify(conf, null, 2)}\n`,
    'Cargo.toml': cargo,
    'build.rs': 'fn main() {\n    tauri_build::build()\n}\n',
    'src/main.rs': main,
    'capabilities/default.json': `${JSON.stringify(capabilities, null, 2)}\n`,
  }
}
