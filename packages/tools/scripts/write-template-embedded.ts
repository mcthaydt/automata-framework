// Writes `src/shared/create-game/template-embedded.ts`: the text of every file under `template-content/`, so the
// starter level can be used where there is no disk (the Automata app on a phone). Run it after changing a file there:
//   node scripts/write-template-embedded.ts          writes the module
//   node scripts/write-template-embedded.ts --check  lists the files where the module differs from the folder
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const FOLDER = fileURLToPath(new URL('../src/shared/create-game/template-content/', import.meta.url))
const MODULE = fileURLToPath(new URL('../src/shared/create-game/template-embedded.ts', import.meta.url))

/** Every file of the folder, by its `/` path below it, sorted. */
export function templateFolderFiles(): Record<string, string> {
  const paths = readdirSync(FOLDER, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => relative(FOLDER, resolve(entry.parentPath, entry.name)).replaceAll('\\', '/'))
    .sort()
  return Object.fromEntries(paths.map((path) => [path, readFileSync(resolve(FOLDER, path), 'utf8')]))
}

export function writeTemplateEmbedded(): void {
  const rows = Object.entries(templateFolderFiles()).map(
    ([path, text]) => `  ${JSON.stringify(path)}: ${JSON.stringify(text)},`,
  )
  writeFileSync(
    MODULE,
    [
      '// Generated by scripts/write-template-embedded.ts from template-content/. Do not edit: change the file there and run it.',
      '',
      "/** The starter level and its editor list, by path below the game's `content/`. */",
      'export const EMBEDDED_TEMPLATE_CONTENT: Readonly<Record<string, string>> = {',
      ...rows,
      '}',
      '',
    ].join('\n'),
  )
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const { EMBEDDED_TEMPLATE_CONTENT } = await import(MODULE)
    const now = templateFolderFiles()
    const drift = Object.keys({ ...now, ...EMBEDDED_TEMPLATE_CONTENT }).filter(
      (path) => now[path] !== EMBEDDED_TEMPLATE_CONTENT[path],
    )
    for (const path of drift) console.error(`template-embedded.ts differs from template-content/${path}`)
    process.exitCode = drift.length === 0 ? 0 : 1
  } else writeTemplateEmbedded()
}
