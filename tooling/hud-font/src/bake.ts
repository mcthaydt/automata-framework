import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { PAGES, type PageDef } from './pages.ts'
import { FONTS_DIR, type FontsRecord, RECORD_FILE, sha256 } from './record.ts'
import { type MsdfBmfontJson, toPixiFont } from './to-pixi.ts'

const require = createRequire(import.meta.url)
// geist's `exports` hide its files from require.resolve, so its folder is read by path.
const GEIST = join(import.meta.dirname, '../node_modules/geist')
const FONT_SIZE = 32
const RANGE = 4
const TEXTURE = '1024,1024'
// The notice is a `/*!` comment, which a build keeps when it is told to (`comments.legal`) and drops when it minifies by
// default; so it is also data (`NOTICE`, which `load-page.ts` registers), which no minifier drops. The OFL asks that
// every copy of the font, in any format, carry the copyright and the licence; `automata ship prepare` adds the full text.
const NOTICE =
  'Geist SemiBold, \u00a9 2023 Vercel, in collaboration with basement.studio. SIL Open Font License 1.1: https://openfontlicense.org (full text: licenses/geist-OFL.txt)'
const HEADER =
  `/*! ${NOTICE} */\n` +
  '// Generated by `pnpm hud-font bake` from Geist SemiBold (packages/automata/licenses/geist-OFL.txt).\n' +
  '// Do not edit: `pnpm hud-font verify` (part of `pnpm check`) compares this file with fonts.record.json.\n'

/** A single-quoted TypeScript string literal with every non-ASCII character escaped, so Biome leaves it alone. */
const literal = (text: string): string => {
  let out = ''
  for (const ch of text) {
    const code = ch.codePointAt(0) as number
    if (ch === '\\' || ch === "'") out += `\\${ch}`
    else if (code === 10) out += '\\n'
    else if (code < 0x20 || code > 0x7e)
      out += code > 0xffff ? `\\u{${code.toString(16)}}` : `\\u${code.toString(16).padStart(4, '0')}`
    else out += ch
  }
  return `'${out}'`
}

const bakePage = (page: PageDef, fontFile: string, work: string) => {
  const charset = join(work, `${page.id}.txt`)
  writeFileSync(charset, page.chars)
  execFileSync(
    process.execPath,
    [
      require.resolve('msdf-bmfont-xml/cli.js'),
      '-f',
      'json',
      '-s',
      String(FONT_SIZE),
      '-r',
      String(RANGE),
      '-t',
      'msdf',
      '-m',
      TEXTURE,
      '-i',
      charset,
      '-o',
      join(work, `${page.id}.png`),
      fontFile,
    ],
    { env: { ...process.env, NO_UPDATE_NOTIFIER: '1' }, stdio: ['ignore', 'ignore', 'inherit'] },
  )
  const json = JSON.parse(readFileSync(join(work, 'Geist-SemiBold.json'), 'utf8')) as MsdfBmfontJson
  const png = readFileSync(join(work, `${page.id}.png`))
  return { json, png }
}

/** Bakes every page and rewrites the generated modules and the record. */
export const bake = (): FontsRecord => {
  const fontFile = join(GEIST, 'dist/fonts/geist-sans/Geist-SemiBold.ttf')
  const work = mkdtempSync(join(tmpdir(), 'hud-font-bake-'))
  mkdirSync(FONTS_DIR, { recursive: true })
  const files: FontsRecord['files'] = {}
  const pages: FontsRecord['pages'] = {}
  const write = (name: string, text: string) => {
    writeFileSync(join(FONTS_DIR, name), text)
    files[name] = { sha256: sha256(text), bytes: Buffer.byteLength(text) }
  }
  try {
    for (const page of PAGES) {
      const { json, png } = bakePage(page, fontFile, work)
      const font = toPixiFont(json, page.id)
      const missing = [...page.chars].filter((ch) => font.chars[ch] === undefined)
      if (missing.length > 0)
        throw new Error(
          `${page.id}: Geist has no glyph for ${missing.map((c) => `U+${c.codePointAt(0)?.toString(16)}`).join(' ')}`,
        )
      write(`${page.id}-chars.ts`, `${HEADER}export const CHARS =\n  ${literal(page.chars)}\n`)
      write(
        `${page.id}-font.ts`,
        `import type { BitmapFontData } from 'pixi.js'\n\n${HEADER}\n` +
          `export const NOTICE =\n  ${literal(NOTICE)}\n\n` +
          `export const FONT: BitmapFontData = JSON.parse(\n  ${literal(JSON.stringify(font))},\n)\n\n` +
          `export const ATLAS_PNG_BASE64 =\n  ${literal(png.toString('base64'))}\n`,
      )
      pages[page.id] = {
        glyphs: Object.keys(font.chars).length,
        atlasBytes: png.length,
        atlasSize: `${json.common.scaleW}x${json.common.scaleH}`,
      }
    }
  } finally {
    rmSync(work, { recursive: true, force: true })
  }
  const geist = JSON.parse(readFileSync(join(GEIST, 'package.json'), 'utf8')) as { version: string }
  const baker = JSON.parse(readFileSync(require.resolve('msdf-bmfont-xml/package.json'), 'utf8')) as {
    version: string
  }
  const record: FontsRecord = {
    source: {
      package: `geist@${geist.version}`,
      file: 'Geist-SemiBold.ttf',
      sha256: sha256(readFileSync(fontFile)),
      licence: 'OFL-1.1',
    },
    baker: `msdf-bmfont-xml@${baker.version}`,
    pages,
    files,
  }
  writeFileSync(join(FONTS_DIR, RECORD_FILE), `${JSON.stringify(record, null, 2)}\n`)
  return record
}
