const BASE64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
/** One signed number as a base-64 VLQ, as a source map writes it. */
function vlq(value: number): string {
  let rest = value < 0 ? (-value << 1) | 1 : value << 1
  let out = ''
  do {
    let digit = rest & 31
    rest >>>= 5
    if (rest > 0) digit |= 32
    out += BASE64[digit]
  } while (rest > 0)
  return out
}
/** Segments `[generatedColumn, sourceIndex]`, per generated line, as a `mappings` string (line 1 of each source). */
function mappings(lines: [number, number][][]): string {
  let source = 0
  return lines
    .map((segments) => {
      let column = 0
      return segments
        .map(([generated, sourceIndex]) => {
          const text = vlq(generated - column) + vlq(sourceIndex - source) + vlq(0) + vlq(0)
          column = generated
          source = sourceIndex
          return text
        })
        .join(',')
    })
    .join(';')
}

describe('packageOf', () => {
  it.each([
    ['../../node_modules/.pnpm/pixi.js@8.22.0/node_modules/pixi.js/lib/a.mjs', 'pixi.js'],
    ['../../node_modules/.pnpm/@scope+pkg@1.0.0/node_modules/@scope/pkg/dist/a.js', '@scope/pkg'],
    ['../../node_modules/.pnpm/effect@3.22.2/node_modules/effect/dist/esm/Effect.js', 'effect'],
    ['../../node_modules/svelte/src/internal/client/a.js', 'svelte'],
    ['../../packages/runtime/src/boot/run-game.ts', '@mcthaydt/automata-runtime'],
    ['../../packages/automata/src/index.ts', '@mcthaydt/automata'],
    ['src/features/player/player.component.ts', '(the game)'],
    ['\0vite/preload-helper.js', '(build helpers)'],
  ])('names %s as %s', (source, name) => {
    expect(packageOf(source)).toBe(name)
  })
})

describe('reportChunks', () => {
  // "aaaa" is source 0 and "bbbbbb" source 1, then line 2 is two bytes of source 1 and four of source 0.
  const chunk = {
    code: 'aaaabbbbbb\nccddddee',
    map: {
      sources: ['../../node_modules/.pnpm/effect@3.22.2/node_modules/effect/a.js', 'src/game.ts'],
      mappings: mappings([
        [
          [0, 0],
          [4, 1],
        ],
        [
          [0, 1],
          [2, 0],
          [6, 1],
        ],
      ]),
    },
  }

  it('counts the generated bytes each package owns, and splits the gzip size by that share', () => {
    // effect: line 1 columns 0 to 4 (4 bytes) and line 2 columns 2 to 6 (4 bytes). The game: 6 + 2 + 2. The newline is nobody's.
    const report = reportChunks([chunk], { gzip: () => 18 })
    expect(report.packages).toEqual([
      { name: '(the game)', rawBytes: 10, gzipBytes: 10 },
      { name: 'effect', rawBytes: 8, gzipBytes: 8 },
    ])
    expect(report.totalRaw).toBe(18)
    expect(report.totalGzip).toBe(18)
  })

  it('adds up several chunks', () => {
    const report = reportChunks([chunk, chunk], { gzip: () => 9 })
    expect(report.totalRaw).toBe(36)
    expect(report.totalGzip).toBeCloseTo(18, 5)
  })

  it('files bytes no segment covers under "(unmapped)"', () => {
    const report = reportChunks([{ code: 'xxxx', map: { sources: ['a.ts'], mappings: '' } }], {
      gzip: () => 2,
    })
    expect(report.packages).toEqual([{ name: '(unmapped)', rawBytes: 4, gzipBytes: 2 }])
  })
})

describe('formatTable', () => {
  it('prints a row per package with its share, and a total', () => {
    const table = formatTable({
      totalRaw: 1500,
      totalGzip: 600,
      packages: [
        { name: 'pixi.js', rawBytes: 1000, gzipBytes: 400 },
        { name: 'effect', rawBytes: 500, gzipBytes: 200 },
      ],
    })
    expect(table).toBe(
      [
        '| Package | Raw (kB) | Gzip (kB) | Share of gzip |',
        '|---|---|---|---|',
        '| pixi.js | 1.00 | 0.40 | 66.7% |',
        '| effect | 0.50 | 0.20 | 33.3% |',
        '| **Total** | 1.50 | 0.60 | 100.0% |',
      ].join('\n'),
    )
  })
})
