// `docs/stack.md`, the "what's inside" page. The prose lives in stack-cards.ts;
// versions and licenses are facts read from the pins and the installed packages, never typed by hand.

import { readdirSync, readFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { type Manifest, pinsFromVersionsDoc } from './pins.ts'

export interface StackCard {
  readonly library: string
  readonly tier: 'Core' | 'Plus'
  /** Installed npm packages whose versions and licenses the card shows. Empty when nothing is installed yet. */
  readonly packages: readonly string[]
  /** A library AF has chosen but not installed yet: its npm packages and the task that installs them. */
  readonly planned?: { readonly packages: readonly string[]; readonly task: string }
  /**
   * A library installed in another repository rather than here (physics, in automata-plus): its
   * npm packages and that repository, which pins them. The page shows no version or license for it.
   */
  readonly elsewhere?: { readonly packages: readonly string[]; readonly repository: string }
  readonly does: string
  readonly why: string
  readonly adds: string
}

export interface StackNote {
  readonly title: string
  readonly body: string
}

export interface StackSource {
  readonly intro: string
  readonly cards: readonly StackCard[]
  readonly notes: readonly StackNote[]
}

export interface PackageFacts {
  readonly name: string
  /** Every pinned version of the package, from docs/versions.md (or the installed manifest for a `file:` tarball). */
  readonly versions: readonly string[]
  /** The installed package.json's `license` field, or a sentence saying it declares none. */
  readonly license: string
  /** Where a package that is not on npm comes from, e.g. a vendored tarball's source commit. */
  readonly source?: string
}

const BANNER =
  '<!-- Generated by `pnpm docs:stack` from tooling/versions/src/stack-cards.ts, docs/versions.md and the installed packages. Do not edit by hand. -->'

/** GitHub's heading anchor: lower case, punctuation dropped, spaces to hyphens. */
function anchor(heading: string): string {
  return heading
    .toLowerCase()
    .replace(/[^a-z0-9 -]/g, '')
    .replace(/ /g, '-')
}

function factsFor(facts: ReadonlyMap<string, PackageFacts>, name: string): PackageFacts {
  const found = facts.get(name)
  if (found === undefined) throw new Error(`${name}: no facts collected`)
  return found
}

function versionText(fact: PackageFacts): string {
  const versions = fact.versions.join(', ')
  return fact.source === undefined ? versions : `${versions} (${fact.source})`
}

function plannedText(card: StackCard): string {
  return `not yet installed; planned for ${card.planned?.task ?? 'an unnamed task'}`
}

function elsewhereText(card: StackCard): string {
  return `installed in ${card.elsewhere?.repository ?? 'another repository'}, not in this repository`
}

function summaryRow(card: StackCard, facts: ReadonlyMap<string, PackageFacts>): string {
  const link = `[${card.library}](#${anchor(card.library)})`
  if (card.packages.length === 0 && card.elsewhere !== undefined)
    return `| ${link} | ${card.tier} | ${elsewhereText(card)} | see there |`
  if (card.packages.length === 0) return `| ${link} | ${card.tier} | ${plannedText(card)} | none yet |`
  const cardFacts = card.packages.map((name) => factsFor(facts, name))
  const versions = cardFacts.map((fact) => `\`${fact.name}\` ${fact.versions.join(', ')}`).join('; ')
  const licenses = [...new Set(cardFacts.map((fact) => fact.license))].join('; ')
  return `| ${link} | ${card.tier} | ${versions} | ${licenses} |`
}

function cardSection(card: StackCard, facts: ReadonlyMap<string, PackageFacts>): string[] {
  const lines = [`## ${card.library}`, '']
  if (card.packages.length > 0) {
    lines.push('| Package | Version | License |', '|---|---|---|')
    for (const name of card.packages) {
      const fact = factsFor(facts, name)
      lines.push(`| \`${name}\` | ${versionText(fact)} | ${fact.license} |`)
    }
    lines.push('')
  }
  if (card.planned !== undefined) {
    const names = card.planned.packages.map((name) => `\`${name}\``).join(', ')
    const text = plannedText(card)
    const label = card.planned.packages.length === 1 ? 'Package' : 'Packages'
    lines.push(`${text[0]?.toUpperCase()}${text.slice(1)}. ${label}: ${names}.`, '')
  }
  if (card.elsewhere !== undefined) {
    const names = card.elsewhere.packages.map((name) => `\`${name}\``).join(', ')
    const text = elsewhereText(card)
    const label = card.elsewhere.packages.length === 1 ? 'Package' : 'Packages'
    lines.push(
      `${text[0]?.toUpperCase()}${text.slice(1)}; its versions are pinned there. ${label}: ${names}.`,
      '',
    )
  }
  lines.push(
    `- **Tier:** ${card.tier}`,
    `- **What it does in AF:** ${card.does}`,
    `- **Why it was chosen:** ${card.why}`,
    `- **What AF adds on top:** ${card.adds}`,
    '',
  )
  return lines
}

/** The whole page. Pure: every fact it prints comes from `facts`. */
export function renderStackPage(source: StackSource, facts: ReadonlyMap<string, PackageFacts>): string {
  const lines = [BANNER, '', "# What's inside", '', source.intro, '']
  lines.push('| Library | Tier | Version | License |', '|---|---|---|---|')
  for (const card of source.cards) lines.push(summaryRow(card, facts))
  lines.push('')
  for (const card of source.cards) lines.push(...cardSection(card, facts))
  for (const note of source.notes) lines.push(`## ${note.title}`, '', note.body, '')
  return `${lines.join('\n').trimEnd()}\n`
}

interface WorkspaceEntry {
  /** Relative to the root, `.` for the root itself. */
  readonly dir: string
  readonly manifest: Manifest
}

const NOT_DECLARED = 'not declared in the installed package'

function readJson<T>(path: string): T | undefined {
  try {
    return JSON.parse(readFileSync(path, 'utf8')) as T
  } catch {
    return undefined
  }
}

/** The root plus every folder pnpm-workspace.yaml names (packages/*, tooling/*, examples/*, examples/*\/*). */
function workspace(root: string): WorkspaceEntry[] {
  const dirs = ['.']
  const children = (dir: string): string[] => {
    try {
      return readdirSync(join(root, dir), { withFileTypes: true })
        .filter((entry) => entry.isDirectory() && entry.name !== 'node_modules')
        .map((entry) => join(dir, entry.name))
        .sort()
    } catch {
      return [] // the group folder does not exist
    }
  }
  dirs.push(...children('packages'), ...children('tooling'))
  for (const example of children('examples')) dirs.push(example, ...children(example))
  const entries: WorkspaceEntry[] = []
  for (const dir of dirs) {
    const manifest = readJson<Manifest>(join(root, dir, 'package.json'))
    if (manifest !== undefined) entries.push({ dir: relative(root, join(root, dir)) || '.', manifest })
  }
  return entries
}

/** The specifier a manifest installs `name` with. Peers are skipped: a peer range is not what gets installed. */
function installSpecifier(manifest: Manifest, name: string): string | undefined {
  return (
    manifest.dependencies?.[name] ?? manifest.devDependencies?.[name] ?? manifest.optionalDependencies?.[name]
  )
}

function mentions(manifest: Manifest, name: string): boolean {
  return installSpecifier(manifest, name) !== undefined || manifest.peerDependencies?.[name] !== undefined
}

/** The commit `vendor/ruken/README.md` records the tarballs as packed from. */
function vendoredRukenCommit(root: string): string {
  const readme = readFileSync(join(root, 'vendor/ruken/README.md'), 'utf8')
  const commit = /RukenApp `main` at `([0-9a-f]+)`/.exec(readme)?.[1]
  if (commit === undefined) throw new Error('vendor/ruken/README.md does not record the RukenApp commit')
  return commit
}

function licenseOf(installed: { license?: unknown }, packageDir: string): string {
  if (typeof installed.license === 'string') return installed.license
  // The old `{ "type": "MIT" }` form some packages still publish.
  const type = (installed.license as { type?: unknown } | undefined)?.type
  if (typeof type === 'string') return type
  const hasLicenseFile = readdirSync(packageDir).some((file) => /^(licen[cs]e|copying)/i.test(file))
  return hasLicenseFile ? "no `license` field; see the package's LICENSE file" : NOT_DECLARED
}

function packageFacts(
  root: string,
  name: string,
  users: readonly WorkspaceEntry[],
  pinned: readonly string[],
): PackageFacts {
  let license: string | undefined
  let vendored: string[] = []
  for (const user of users) {
    const specifier = installSpecifier(user.manifest, name) ?? ''
    const packageDir = join(root, user.dir, 'node_modules', name)
    const installed = readJson<{ version?: string; license?: unknown }>(join(packageDir, 'package.json'))
    if (installed === undefined) throw new Error(`${name}: not installed in ${user.dir}; run pnpm install`)
    if (specifier.startsWith('file:')) {
      vendored = [...new Set([...vendored, installed.version ?? 'unknown'])]
    } else if (installed.version !== specifier) {
      throw new Error(
        `${name}: ${user.dir} has ${installed.version} installed but pins ${specifier}; run pnpm install`,
      )
    }
    license ??= licenseOf(installed, packageDir)
  }
  if (pinned.length > 0) return { name, versions: pinned, license: license ?? NOT_DECLARED }
  if (vendored.length === 0) throw new Error(`${name}: no row in docs/versions.md`)
  return {
    name,
    versions: vendored,
    license: license ?? NOT_DECLARED,
    source: `vendored tarball, RukenApp \`${vendoredRukenCommit(root)}\``,
  }
}

/**
 * Versions and licenses for every package the cards name, read from docs/versions.md and the installed
 * packages. Throws, naming the package, on anything that would make the page claim something unverified.
 */
export function collectStackFacts(root: string, cards: readonly StackCard[]): Map<string, PackageFacts> {
  const entries = workspace(root)
  const pins = pinsFromVersionsDoc(readFileSync(join(root, 'docs/versions.md'), 'utf8'))
  const facts = new Map<string, PackageFacts>()
  for (const card of cards) {
    for (const name of card.planned?.packages ?? []) {
      const user = entries.find((entry) => mentions(entry.manifest, name))
      if (user !== undefined) {
        throw new Error(
          `${name}: planned for ${card.planned?.task} but ${user.dir} depends on it now; move it to the card's packages`,
        )
      }
    }
    if (card.elsewhere !== undefined && card.packages.length > 0) {
      throw new Error(
        `${card.library}: a card held in ${card.elsewhere.repository} lists no packages of its own; move ${card.packages.join(', ')} to elsewhere or drop elsewhere`,
      )
    }
    for (const name of card.elsewhere?.packages ?? []) {
      const user = entries.find((entry) => mentions(entry.manifest, name))
      if (user !== undefined) {
        throw new Error(
          `${name}: held in ${card.elsewhere?.repository} but ${user.dir} depends on it now; move it to the card's packages`,
        )
      }
    }
    for (const name of card.packages) {
      const users = entries.filter((entry) => installSpecifier(entry.manifest, name) !== undefined)
      if (users.length === 0) throw new Error(`${name}: no package.json depends on it`)
      const pinned = pins.filter((pin) => pin.name === name).map((pin) => pin.version)
      facts.set(name, packageFacts(root, name, users, pinned))
    }
  }
  return facts
}
