// PRODUCT.4: `docs/stack.md`, the "what's inside" page (PRODUCT spec §8). The prose lives in stack-cards.ts;
// versions and licenses are facts read from the pins and the installed packages, never typed by hand.

export interface StackCard {
  readonly library: string
  readonly tier: 'Core' | 'Plus'
  /** Installed npm packages whose versions and licenses the card shows. Empty when nothing is installed yet. */
  readonly packages: readonly string[]
  /** A library AF has chosen but not installed yet: its npm packages and the task that installs them. */
  readonly planned?: { readonly packages: readonly string[]; readonly task: string }
  readonly does: string
  readonly why: string
  readonly adds: string
}

export interface StackNote {
  readonly title: string
  readonly body: string
}

export interface StackSource {
  readonly intro: string
  readonly cards: readonly StackCard[]
  readonly notes: readonly StackNote[]
}

export interface PackageFacts {
  readonly name: string
  /** Every pinned version of the package, from docs/versions.md (or the installed manifest for a `file:` tarball). */
  readonly versions: readonly string[]
  /** The installed package.json's `license` field, or a sentence saying it declares none. */
  readonly license: string
  /** Where a package that is not on npm comes from, e.g. a vendored tarball's source commit. */
  readonly source?: string
}

const BANNER =
  '<!-- Generated by `pnpm docs:stack` from tooling/versions/src/stack-cards.ts, docs/versions.md and the installed packages. Do not edit by hand. -->'

/** GitHub's heading anchor: lower case, punctuation dropped, spaces to hyphens. */
function anchor(heading: string): string {
  return heading
    .toLowerCase()
    .replace(/[^a-z0-9 -]/g, '')
    .replace(/ /g, '-')
}

function factsFor(facts: ReadonlyMap<string, PackageFacts>, name: string): PackageFacts {
  const found = facts.get(name)
  if (found === undefined) throw new Error(`${name}: no facts collected`)
  return found
}

function versionText(fact: PackageFacts): string {
  const versions = fact.versions.join(', ')
  return fact.source === undefined ? versions : `${versions} (${fact.source})`
}

function plannedText(card: StackCard): string {
  return `not yet installed; planned for ${card.planned?.task ?? 'an unnamed task'}`
}

function summaryRow(card: StackCard, facts: ReadonlyMap<string, PackageFacts>): string {
  const link = `[${card.library}](#${anchor(card.library)})`
  if (card.packages.length === 0) return `| ${link} | ${card.tier} | ${plannedText(card)} | none yet |`
  const cardFacts = card.packages.map((name) => factsFor(facts, name))
  const versions = cardFacts.map((fact) => `\`${fact.name}\` ${fact.versions.join(', ')}`).join('; ')
  const licenses = [...new Set(cardFacts.map((fact) => fact.license))].join('; ')
  return `| ${link} | ${card.tier} | ${versions} | ${licenses} |`
}

function cardSection(card: StackCard, facts: ReadonlyMap<string, PackageFacts>): string[] {
  const lines = [`## ${card.library}`, '']
  if (card.packages.length > 0) {
    lines.push('| Package | Version | License |', '|---|---|---|')
    for (const name of card.packages) {
      const fact = factsFor(facts, name)
      lines.push(`| \`${name}\` | ${versionText(fact)} | ${fact.license} |`)
    }
    lines.push('')
  }
  if (card.planned !== undefined) {
    const names = card.planned.packages.map((name) => `\`${name}\``).join(', ')
    const text = plannedText(card)
    lines.push(`${text[0]?.toUpperCase()}${text.slice(1)} (${names}).`, '')
  }
  lines.push(
    `- **Tier:** ${card.tier}`,
    `- **What it does in AF:** ${card.does}`,
    `- **Why it was chosen:** ${card.why}`,
    `- **What AF adds on top:** ${card.adds}`,
    '',
  )
  return lines
}

/** The whole page. Pure: every fact it prints comes from `facts`. */
export function renderStackPage(source: StackSource, facts: ReadonlyMap<string, PackageFacts>): string {
  const lines = [BANNER, '', "# What's inside", '', source.intro, '']
  lines.push('| Library | Tier | Version | License |', '|---|---|---|---|')
  for (const card of source.cards) lines.push(summaryRow(card, facts))
  lines.push('')
  for (const card of source.cards) lines.push(...cardSection(card, facts))
  for (const note of source.notes) lines.push(`## ${note.title}`, '', note.body, '')
  return `${lines.join('\n').trimEnd()}\n`
}
