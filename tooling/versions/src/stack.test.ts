import { describe, expect, it } from 'vitest'
import { type PackageFacts, renderStackPage, type StackSource } from './stack.ts'

const source: StackSource = {
  intro: 'The libraries AF is built on.',
  cards: [
    {
      library: 'Zod',
      tier: 'Core',
      packages: ['zod'],
      does: 'Every schema.',
      why: 'Ruken uses it.',
      adds: 'Jitless mode under the no-eval entry.',
    },
    {
      library: 'Paraglide',
      tier: 'Core',
      packages: [],
      planned: { packages: ['@inlang/paraglide-js'], task: 'PRODUCT.L' },
      does: 'Typed messages.',
      why: "FloorFifty's setup.",
      adds: 'Negotiation from the session locale.',
    },
  ],
  notes: [{ title: 'Why Rapier and not Planck', body: 'One engine, one parity suite.' }],
}

const facts = new Map<string, PackageFacts>([['zod', { name: 'zod', versions: ['4.6.5'], license: 'MIT' }]])

describe('renderStackPage', () => {
  const page = renderStackPage(source, facts)

  it('starts with the generated-file banner and the intro', () => {
    expect(page.split('\n').slice(0, 5)).toEqual([
      '<!-- Generated by `pnpm docs:stack` from tooling/versions/src/stack-cards.ts, docs/versions.md and the installed packages. Do not edit by hand. -->',
      '',
      "# What's inside",
      '',
      'The libraries AF is built on.',
    ])
  })

  it('has one summary row per library', () => {
    expect(page).toContain('| [Zod](#zod) | Core | `zod` 4.6.5 | MIT |')
    expect(page).toContain(
      '| [Paraglide](#paraglide) | Core | not yet installed; planned for PRODUCT.L | none yet |',
    )
  })

  it('renders an installed card with its package table and the four lines', () => {
    expect(page).toContain(
      [
        '## Zod',
        '',
        '| Package | Version | License |',
        '|---|---|---|',
        '| `zod` | 4.6.5 | MIT |',
        '',
        '- **Tier:** Core',
        '- **What it does in AF:** Every schema.',
        '- **Why it was chosen:** Ruken uses it.',
        '- **What AF adds on top:** Jitless mode under the no-eval entry.',
      ].join('\n'),
    )
  })

  it('says a planned library is not yet installed and invents no version or license', () => {
    const card = page.slice(page.indexOf('## Paraglide'), page.indexOf('## Why Rapier'))
    expect(card).toContain('Not yet installed; planned for PRODUCT.L (`@inlang/paraglide-js`).')
    expect(card).not.toContain('| Package |')
  })

  it('ends with the notes, then a single newline', () => {
    expect(page.endsWith('## Why Rapier and not Planck\n\nOne engine, one parity suite.\n')).toBe(true)
  })

  it('fails when an installed package has no facts', () => {
    expect(() => renderStackPage(source, new Map())).toThrow('zod: no facts collected')
  })
})
