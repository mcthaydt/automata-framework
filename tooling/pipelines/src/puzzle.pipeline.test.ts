// The `puzzle` pipeline (M6 spec §4.5, M6.6b, P-d) through the platform's router on a temporary scene folder: `run`
// writes the analysis, the doc and the audit and is cached the second time; `check` passes a sound puzzle, fails a
// softlock naming its route, and fails a doc that is stale or edited by hand.
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { pathToFileURL } from 'node:url'
import { FilesLive, ProcessRunnerLive } from '@mcthaydt/automata-node'
import { Effect, Layer } from 'effect'
import { afterEach, describe, expect, it } from 'vitest'
import { puzzlePipeline, puzzlePipeSpec } from './puzzle.pipeline.ts'
import { route } from './router.ts'

const resolve = createRequire(import.meta.url).resolve
const TOY = resolve('@mcthaydt/automata-puzzle/testing/toy-scene.pipe')
const SOFTLOCK = resolve('@mcthaydt/automata-puzzle/testing/softlock-scene.pipe')
const temps: string[] = []
afterEach(() => {
  for (const dir of temps.splice(0)) rmSync(dir, { recursive: true, force: true })
})
function folder(module: string): string {
  const dir = mkdtempSync(join(tmpdir(), 'pipe-puzzle-'))
  temps.push(dir)
  writeFileSync(join(dir, 'pipeline.toml'), '[budget]\n')
  writeFileSync(
    join(dir, 'scene.ts'),
    `export { puzzle } from ${JSON.stringify(pathToFileURL(module).href)}\n`,
  )
  writeFileSync(join(dir, 'toy.puzzle.toml'), '# the toy puzzle\n')
  writeFileSync(join(dir, 'puzzle.pipe.toml'), 'scene = "./scene.ts"\nsources = ["toy.puzzle.toml"]\n')
  return dir
}
const layers = Layer.mergeAll(FilesLive, ProcessRunnerLive)
const pipe = (...argv: string[]) =>
  Effect.runPromise(Effect.provide(route([...argv, '--json'], [puzzlePipeline], []), layers)).then((out) => ({
    exit: out.exit,
    json: JSON.parse(out.stdout) as Record<string, unknown>,
  }))
const checks = (json: Record<string, unknown>) =>
  (json.data as { checks: { id: string; ok: boolean; detail: string }[] }).checks

describe('puzzle.pipe.toml', () => {
  it('parses a scene module and an optional entry; a missing scene fails at its path', () => {
    expect(puzzlePipeSpec.safeParse({ scene: './scene.ts', entry: 'start' }).success).toBe(true)
    const bad = puzzlePipeSpec.safeParse({ entry: 'start' })
    expect(bad.success ? [] : bad.error.issues.map((i) => i.path)).toEqual([['scene']])
  })
})

describe('automata pipe puzzle', () => {
  it('writes the analysis, the doc and the audit, is cached the second time, and passes check', async () => {
    const dir = folder(TOY)
    expect((await pipe('puzzle', 'run', dir)).exit).toBe(0)
    for (const file of ['reports/puzzle.json', 'puzzle.md', 'reports/audit.json', 'audit.md'])
      expect(existsSync(join(dir, file)), file).toBe(true)
    expect(readFileSync(join(dir, 'puzzle.md'), 'utf8')).toMatch(/^<!-- Generated by /)
    const again = await pipe('puzzle', 'run', dir)
    expect((again.json.stages as { state: string }[]).map((s) => s.state)).toEqual([
      'skipped',
      'skipped',
      'skipped',
    ])
    const check = await pipe('puzzle', 'check', dir)
    expect(check.exit).toBe(0)
    for (const id of ['validate', 'solvable', 'softlocks', 'hints', 'keys', 'doc'])
      expect(checks(check.json).find((c) => c.id === id)?.ok, id).toBe(true)
  })

  it('fails check on a softlock, naming the locking route (P-d)', async () => {
    const dir = folder(SOFTLOCK)
    await pipe('puzzle', 'run', dir)
    const check = await pipe('puzzle', 'check', dir)
    expect(check.exit).not.toBe(0)
    expect(checks(check.json).find((c) => c.id === 'softlocks')).toEqual({
      id: 'softlocks',
      ok: false,
      detail: '1 softlock in 4 states: start: drawer > cupboard (key)',
    })
  })

  it('fails check on a doc that is stale or edited by hand', async () => {
    const dir = folder(TOY)
    await pipe('puzzle', 'run', dir)
    writeFileSync(join(dir, 'toy.puzzle.toml'), '# the toy puzzle, changed\n')
    expect(checks((await pipe('puzzle', 'check', dir)).json).find((c) => c.id === 'doc')?.ok).toBe(false)
    await pipe('puzzle', 'run', dir)
    expect(checks((await pipe('puzzle', 'check', dir)).json).find((c) => c.id === 'doc')?.ok).toBe(true)
    writeFileSync(
      join(dir, 'puzzle.md'),
      `${readFileSync(join(dir, 'puzzle.md'), 'utf8')}\nA hand-written note.\n`,
    )
    expect(checks((await pipe('puzzle', 'check', dir)).json).find((c) => c.id === 'doc')).toMatchObject({
      ok: false,
    })
  })
})
